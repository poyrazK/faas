// sec11_host_age_e2e_test.go — §11 host.age 0400 root:root +
// systemd `LoadCredential=` decouple (every-PR layer-down pin).
//
// Spec §11: "/etc/faas/secrets/host.age 0400 root:root." apid reads
// the identity through the systemd `LoadCredential=` indirection
// (deploy/systemd/faas-apid.service:50-51 +
// deploy/digitalocean/systemd/faas-apid.service:37-38) — NOT from
// the on-disk file. The original PR #237 commit `4add80d` aligned
// the in-process mode check + the two `deploy/{,digitalocean/}systemd/
// faas-apid.service` files but left two gaps:
//
//  1. No test pinned the cross-process decouple end-to-end. A
//     regression that swapped `%d/...` for `/etc/faas/secrets/host.age`
//     passed the in-process perm pin without anyone noticing.
//  2. The ansible-side service file at
//     deploy/ansible/roles/control_plane_service/files/faas-apid.service:49
//     was MISSING the `LoadCredential=` indirection entirely (fixed
//     in commit 4c46dd8 / PR #350's third commit), so ansible deploys
//     didn't have the decouple.
//
// This file closes the test-side gap. The three tests run on every-PR
// CI (no build tag, no /dev/kvm, no root) and pin:
//
//   - LoadCredentialDecouple: apid boots cleanly when given an
//     env-var path that is NOT the on-disk file (simulating the
//     systemd credential-copy indirection). The on-disk file
//     remains unread by apid.
//   - OnDiskIs0400RootRoot: the on-disk fixture file generated by
//     the test holds mode 0o400 (the LoadCredential source-of-truth
//     the ansible role asserts in main.yml:137-141).
//   - OnDiskInsecurePermsFailsFast: a regression that points apid
//     at the on-disk file with deliberately-loose perms (0440)
//     must fail-fast with ErrHostKeyInsecurePerms in the log,
//     proving the tripwire survives direct-file access.
//
// Same shape as cmd/e2e/sec11_memory_max_e2e_test.go and
// cmd/e2e/sec11_sweep_test.go — every-PR, no metal gate. The
// production `deploy/systemd/faas-apid.service` LoadCredential=
// line is the runtime guarantee; this file is the regression
// net that catches an in-tree drift before it lands.

