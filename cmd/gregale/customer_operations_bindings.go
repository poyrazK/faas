package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"

	"github.com/onebox-faas/faas/pkg/operationbindings"
)

type customerOperationBindingsCommand struct {
	source                        customerOperationDeveloperCommand
	language, output, packageName string
	check                         bool
}

func parseCustomerOperationBindings(args []string) (customerOperationBindingsCommand, error) {
	var c customerOperationBindingsCommand
	fs := newFlagSet("customer-operations bindings", flag.ContinueOnError)
	fs.StringVar(&c.source.app, "app", "", "selected manifest app")
	fs.StringVar(&c.source.plan, "plan", "", "explicit target plan")
	fs.StringVar(&c.source.dir, "dir", ".", "source directory")
	fs.StringVar(&c.language, "language", "", "typescript, javascript, go or python")
	fs.StringVar(&c.output, "output", "", "generated application module")
	fs.StringVar(&c.packageName, "package", "workflowbindings", "Go package name")
	fs.BoolVar(&c.check, "check", false, "fail if output differs; do not write")
	if err := parseInterspersed(fs, args); err != nil {
		return c, err
	}
	if fs.NArg() != 0 || c.source.app == "" || c.source.plan == "" || c.language == "" || c.output == "" {
		return c, fmt.Errorf("bindings requires --app, --plan, --language and --output, with no positional arguments")
	}
	return c, nil
}

func cmdCustomerOperationBindings(args []string) int {
	c, err := parseCustomerOperationBindings(args)
	if err == nil {
		err = runCustomerOperationBindings(c, osStdout)
	}
	if err != nil {
		return printErr("Workflow binding generation failed", err)
	}
	return 0
}

func runCustomerOperationBindings(c customerOperationBindingsCommand, out io.Writer) error {
	report, err := validateCustomerOperationSource(c.source)
	if err != nil {
		return err
	}
	sort.Slice(report.Definitions, func(i, j int) bool { return report.Definitions[i].Name < report.Definitions[j].Name })
	canonical, err := json.Marshal(report.Definitions)
	if err != nil {
		return err
	}
	digest := sha256.Sum256(canonical)
	contract := operationbindings.Contract{App: report.App, SHA256: hex.EncodeToString(digest[:])}
	for _, definition := range report.Definitions {
		operation := operationbindings.Operation{Name: definition.Name, Revision: definition.Revision}
		for name := range definition.Spec.Milestones {
			operation.Milestones = append(operation.Milestones, name)
		}
		for _, step := range definition.Spec.WorkflowSteps {
			workflow := operationbindings.Workflow{
				Name: step.Workflow, Version: step.Version, States: step.States, TerminalStates: step.TerminalStates,
				TransitionsDeclared: step.TransitionsDeclared,
			}
			for _, edge := range step.Transitions {
				workflow.Transitions = append(workflow.Transitions, operationbindings.Transition{From: edge.From, To: edge.To, RequiredMilestones: edge.RequiredMilestones})
			}
			operation.Workflows = append(operation.Workflows, workflow)
		}
		contract.Operations = append(contract.Operations, operation)
	}
	body, err := operationbindings.Render(contract, c.language, c.packageName)
	if err != nil {
		return err
	}
	if c.check {
		existing, err := os.ReadFile(c.output)
		if err != nil {
			return fmt.Errorf("read bindings for --check: %w", err)
		}
		if !bytes.Equal(existing, body) {
			return fmt.Errorf("workflow bindings are stale: regenerate %s without --check", c.output)
		}
	} else if err := writeCustomerOperationBindings(c.output, body); err != nil {
		return err
	}
	if jsonOutput {
		return json.NewEncoder(out).Encode(map[string]any{"output": c.output, "checked": c.check, "contract_sha256": contract.SHA256})
	}
	action := "Generated"
	if c.check {
		action = "Verified"
	}
	_, err = fmt.Fprintf(out, "%s workflow bindings: %s\n", action, c.output)
	return err
}

func writeCustomerOperationBindings(path string, body []byte) error {
	info, err := os.Lstat(path)
	if err == nil {
		if !info.Mode().IsRegular() {
			return fmt.Errorf("bindings output must be a regular file")
		}
		existing, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}
		if !bytes.HasPrefix(existing, []byte("// Code generated by gregale customer-operations bindings;")) && !bytes.HasPrefix(existing, []byte("# Code generated by gregale customer-operations bindings;")) {
			return fmt.Errorf("refusing to replace a file not generated by customer-operations bindings: %s", path)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	file, err := os.CreateTemp(filepath.Dir(path), ".workflow-bindings-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(file.Name()) }()
	if _, err = file.Write(body); err == nil {
		err = file.Chmod(0644)
	}
	closeErr := file.Close()
	if err != nil {
		return err
	}
	if closeErr != nil {
		return closeErr
	}
	return os.Rename(file.Name(), path)
}
