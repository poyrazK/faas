// adr: 20261027123814 — Data API contract tasks use the Data API's own routes,
// and fall back to app tasks on an apid that predates them.
package main_test

import (
	"encoding/json"
	"net/http"
	"net/http/httptest"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"sync"
	"testing"

	main "github.com/onebox-faas/faas/cmd/gregale"
	"github.com/onebox-faas/faas/pkg/api"
)

func TestDataAPITypesPollsItsContractTask(t *testing.T) {
	for _, legacy := range []bool{false, true} {
		name := map[bool]string{false: "contract-route", true: "legacy-apid"}[legacy]
		t.Run(name, func(t *testing.T) {
			main.ResetJSONOut(t)
			content := "// Generated by gregale data-api types. Do not edit.\n// Schema fingerprint: " + strings.Repeat("b", 64) + "\nexport type Database = {}\n"
			var mu sync.Mutex
			var seen []string
			srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				mu.Lock()
				seen = append(seen, r.Method+" "+r.URL.Path)
				mu.Unlock()
				w.Header().Set("Content-Type", "application/json")
				queued := api.AppTaskResponse{ID: "task-7", DeploymentID: "live", Status: api.AppTaskStatusQueued}
				done := api.AppTaskResponse{ID: "task-7", DeploymentID: "live", Status: api.AppTaskStatusSucceeded, StdoutTail: content}
				switch r.Method + " " + r.URL.Path {
				case "POST /v1/apps/notes/data-api/contract-tasks":
					if legacy {
						w.Header().Set("Content-Type", "application/problem+json")
						w.WriteHeader(http.StatusNotFound)
						_ = json.NewEncoder(w).Encode(api.Problem{Status: http.StatusNotFound, Code: api.CodeNotFound, Title: "Not found", Detail: "no such API route"})
						return
					}
					var request api.CreateDataAPIContractTaskRequest
					if json.NewDecoder(r.Body).Decode(&request) != nil || request.Kind != api.DataAPIContractTypes {
						t.Errorf("contract task request kind = %q", request.Kind)
					}
					w.WriteHeader(http.StatusAccepted)
					_ = json.NewEncoder(w).Encode(queued)
				case "GET /v1/apps/notes/data-api/contract-tasks/task-7":
					_ = json.NewEncoder(w).Encode(done)
				case "POST /v1/apps/notes/tasks":
					var request api.CreateAppTaskRequest
					if json.NewDecoder(r.Body).Decode(&request) != nil || !slices.Equal(request.Command, api.DataAPIContractTypes.Command()) || request.TimeoutSeconds != api.DataAPIContractTaskTimeoutSeconds {
						t.Errorf("legacy app task = %+v", request)
					}
					w.WriteHeader(http.StatusAccepted)
					_ = json.NewEncoder(w).Encode(queued)
				case "GET /v1/apps/notes/tasks/task-7":
					_ = json.NewEncoder(w).Encode(done)
				default:
					t.Errorf("unexpected request %s %s", r.Method, r.URL.Path)
					http.NotFound(w, r)
				}
			}))
			defer srv.Close()
			t.Setenv("FAAS_API", srv.URL)
			t.Setenv("FAAS_TOKEN", "fp_live_test")
			path := filepath.Join(t.TempDir(), "types.ts")
			if code := main.CmdDataAPI([]string{"types", "notes", "--output", path}); code != 0 {
				t.Fatalf("types exit = %d", code)
			}
			if got, _ := os.ReadFile(path); string(got) != content {
				t.Fatalf("types = %q", got)
			}
			want := []string{"POST /v1/apps/notes/data-api/contract-tasks", "GET /v1/apps/notes/data-api/contract-tasks/task-7"}
			if legacy {
				want = []string{"POST /v1/apps/notes/data-api/contract-tasks", "POST /v1/apps/notes/tasks", "GET /v1/apps/notes/tasks/task-7"}
			}
			mu.Lock()
			defer mu.Unlock()
			if !slices.Equal(seen, want) {
				t.Fatalf("requests = %v, want %v", seen, want)
			}
		})
	}
}
