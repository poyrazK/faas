const customerOperationTypesMarker = "// Code generated by gregale customer-operations types; DO NOT EDIT."

type customerOperationTypesResult struct {
	Output     string   `json:"output"`
	Operations int      `json:"operations"`
	Types      []string `json:"types"`
	Status     string   `json:"status,omitempty"`
}

type generatedCustomerOperationTypes struct {
	inputName    string
	outputName   string
	inputSchema  any
	outputSchema any
}

type generatedSchemaAlias struct {
	name   string
	ref    string
	schema any
	usable bool
}

func generateCustomerOperationTypes(report customerOperationValidation) ([]byte, []string, error) {
	if len(report.Definitions) == 0 {
		return nil, nil, fmt.Errorf("no operation schemas found for the selected app")
	}
	definitions := append([]customerOperationValidatedDefinition(nil), report.Definitions...)
	sort.Slice(definitions, func(i, j int) bool { return definitions[i].Name < definitions[j].Name })
	counts := map[string]int{}
	for _, definition := range definitions {
		counts[customerOperationTypeStem(definition.Name)]++
	}
	types := make([]generatedCustomerOperationTypes, 0, len(definitions))
	publicNames := make([]string, 0, len(definitions)*2)
	for _, definition := range definitions {
		stem := customerOperationTypeStem(definition.Name)
		if counts[stem] > 1 {
			stem += "Operation" + shortTypeHash(definition.Name)
		}
		inputName, outputName := stem+"Input", stem+"Output"
		inputSchema, err := decodeCustomerOperationSchema(definition.Spec.InputSchema)
		if err != nil {
			return nil, nil, fmt.Errorf("operation %q input schema: %w", definition.Name, err)
		}
		outputSchema, err := decodeCustomerOperationSchema(definition.Spec.OutputSchema)
		if err != nil {
			return nil, nil, fmt.Errorf("operation %q output schema: %w", definition.Name, err)
		}
		types = append(types, generatedCustomerOperationTypes{inputName: inputName, outputName: outputName, inputSchema: inputSchema, outputSchema: outputSchema})
		publicNames = append(publicNames, inputName, outputName)
	}

	var out strings.Builder
	out.WriteString(customerOperationTypesMarker + "\n")
	out.WriteString("// These declarations project JSON Schema shapes. Runtime constraints remain enforced by Gregale.\n\n")
	for _, operation := range types {
		inputRefs, inputAliases := customerOperationSchemaAliases(operation.inputSchema, operation.inputName)
		outputRefs, outputAliases := customerOperationSchemaAliases(operation.outputSchema, operation.outputName)
		fmt.Fprintf(&out, "export type %s = %s;\n", operation.inputName, customerOperationSchemaType(operation.inputSchema, operation.inputName, inputRefs, 0))
		writeCustomerOperationSchemaAliases(&out, inputAliases, inputRefs)
		fmt.Fprintf(&out, "\nexport type %s = %s;\n", operation.outputName, customerOperationSchemaType(operation.outputSchema, operation.outputName, outputRefs, 0))
		writeCustomerOperationSchemaAliases(&out, outputAliases, outputRefs)
		out.WriteByte('\n')
	}
	return []byte(out.String()), publicNames, nil
}

func decodeCustomerOperationSchema(raw json.RawMessage) (any, error) {
	decoder := json.NewDecoder(strings.NewReader(string(raw)))
	decoder.UseNumber()
	var schema any
	if err := decoder.Decode(&schema); err != nil {
		return nil, err
	}
	return schema, nil
}

func customerOperationTypeStem(name string) string {
	var out strings.Builder
	upper := true
	for _, r := range name {
		if r == '-' {
			upper = true
			continue
		}
		if upper {
			if r >= 'a' && r <= 'z' {
				r -= 'a' - 'A'
			}
			upper = false
		}
		out.WriteRune(r)
	}
	return out.String()
}

func shortTypeHash(value string) string {
	sum := sha256.Sum256([]byte(value))
	return hex.EncodeToString(sum[:8])
}

func customerOperationSchemaAliases(schema any, rootName string) (map[string]string, []generatedSchemaAlias) {
	refs := map[string]bool{}
	collectCustomerOperationSchemaRefs(schema, refs)
	refNames := map[string]string{"#": rootName}
	ordered := make([]string, 0, len(refs))
	for ref := range refs {
		if ref != "#" {
			ordered = append(ordered, ref)
		}
	}
	sort.Strings(ordered)
	aliases := make([]generatedSchemaAlias, 0, len(ordered))
	for _, ref := range ordered {
		name := rootName + "Ref" + shortTypeHash(ref)
		refNames[ref] = name
		target, ok := resolveCustomerOperationSchemaPointer(schema, ref)
		aliases = append(aliases, generatedSchemaAlias{name: name, ref: ref, schema: target, usable: ok})
	}
	return refNames, aliases
}

func collectCustomerOperationSchemaRefs(value any, refs map[string]bool) {
	object, ok := value.(map[string]any)
	if !ok {
		return
	}
	for _, keyword := range []string{"$ref", "$dynamicRef", "$recursiveRef"} {
		if ref, ok := object[keyword].(string); ok && ref != "" && strings.HasPrefix(ref, "#") {
			refs[ref] = true
		}
	}
	for keyword, child := range object {
		switch keyword {
		case "$defs", "definitions", "properties", "patternProperties", "dependentSchemas":
			if children, ok := child.(map[string]any); ok {
				for _, schema := range children {
					collectCustomerOperationSchemaRefs(schema, refs)
				}
			}
		case "allOf", "anyOf", "oneOf", "prefixItems":
			if children, ok := child.([]any); ok {
				for _, schema := range children {
					collectCustomerOperationSchemaRefs(schema, refs)
				}
			}
		case "items":
			if children, ok := child.([]any); ok {
				for _, schema := range children {
					collectCustomerOperationSchemaRefs(schema, refs)
				}
			} else {
				collectCustomerOperationSchemaRefs(child, refs)
			}
		case "additionalProperties", "unevaluatedProperties", "unevaluatedItems", "contains", "not", "if", "then", "else", "propertyNames", "contentSchema", "additionalItems":
			collectCustomerOperationSchemaRefs(child, refs)
		}
	}
}

func resolveCustomerOperationSchemaPointer(root any, ref string) (any, bool) {
	if ref == "#" {
		return root, true
	}
	if !strings.HasPrefix(ref, "#/") {
		return nil, false // Local anchors are valid JSON Schema, but not JSON Pointers.
	}
	fragment, err := url.PathUnescape(strings.TrimPrefix(ref, "#"))
	if err != nil {
		return nil, false
	}
	current := root
	for _, token := range strings.Split(strings.TrimPrefix(fragment, "/"), "/") {
		token = strings.NewReplacer("~1", "/", "~0", "~").Replace(token)
		switch value := current.(type) {
		case map[string]any:
			var ok bool
			current, ok = value[token]
			if !ok {
				return nil, false
			}
		case []any:
			index, err := strconv.Atoi(token)
			if err != nil || index < 0 || index >= len(value) {
				return nil, false
			}
			current = value[index]
		default:
			return nil, false
		}
	}
	return current, true
}

func writeCustomerOperationSchemaAliases(out *strings.Builder, aliases []generatedSchemaAlias, refs map[string]string) {
	for _, alias := range aliases {
		schemaType := "unknown"
		if alias.usable {
			schemaType = customerOperationSchemaType(alias.schema, alias.name, refs, 0)
		} else {
			fmt.Fprintf(out, "// %s uses unknown because %s is a local anchor, not a JSON Pointer.\n", alias.name, strconv.Quote(alias.ref))
		}
		fmt.Fprintf(out, "export type %s = %s;\n", alias.name, schemaType)
	}
}

func customerOperationSchemaType(schema any, rootName string, refs map[string]string, depth int) string {
	if depth > 64 {
		return "unknown"
	}
	if boolean, ok := schema.(bool); ok {
		if boolean {
			return "unknown"
		}
		return "never"
	}
	object, ok := schema.(map[string]any)
	if !ok {
		return "unknown"
	}
	parts := make([]string, 0, 5)
	if values, ok := object["enum"].([]any); ok {
		parts = append(parts, parenthesizeCustomerOperationUnion(customerOperationEnumType(values)))
	}
	if value, ok := object["const"]; ok {
		parts = append(parts, customerOperationLiteralType(value))
	}
	for _, keyword := range []string{"$ref", "$dynamicRef", "$recursiveRef"} {
		if ref, ok := object[keyword].(string); ok && ref != "" {
			if name, found := refs[ref]; found {
				parts = append(parts, name)
			} else {
				parts = append(parts, "unknown")
			}
			break
		}
	}
	if core := customerOperationSchemaCoreType(object, rootName, refs, depth); core != "unknown" {
		parts = append(parts, parenthesizeCustomerOperationUnion(core))
	}
	if schemas, ok := object["allOf"].([]any); ok {
		for _, child := range schemas {
			parts = append(parts, parenthesizeCustomerOperationUnion(customerOperationSchemaType(child, rootName, refs, depth+1)))
		}
	}
	for _, keyword := range []string{"anyOf", "oneOf"} {
		if schemas, ok := object[keyword].([]any); ok {
			choices := make([]string, 0, len(schemas))
			for _, child := range schemas {
				choices = append(choices, customerOperationSchemaType(child, rootName, refs, depth+1))
			}
			if len(choices) == 0 {
				parts = append(parts, "never")
			} else {
				parts = append(parts, "("+strings.Join(choices, " | ")+")")
			}
		}
	}
	if len(parts) == 0 {
		return "unknown"
	}
	return strings.Join(parts, " & ")
}

func parenthesizeCustomerOperationUnion(value string) string {
	if strings.Contains(value, " | ") {
		return "(" + value + ")"
	}
	return value
}

func customerOperationSchemaCoreType(schema map[string]any, rootName string, refs map[string]string, depth int) string {
	types := make([]string, 0, 4)
	switch value := schema["type"].(type) {
	case string:
		types = append(types, value)
	case []any:
		for _, item := range value {
			if item, ok := item.(string); ok {
				types = append(types, item)
			}
		}
	}
	if len(types) == 0 {
		return "unknown"
	}
	result := make([]string, 0, len(types))
	for _, schemaType := range types {
		var expression string
		switch schemaType {
		case "object":
			expression = customerOperationObjectType(schema, rootName, refs, depth)
		case "array":
			expression = customerOperationArrayType(schema, rootName, refs, depth)
		case "string":
			expression = "string"
		case "integer", "number":
			expression = "number"
		case "boolean":
			expression = "boolean"
		case "null":
			expression = "null"
		default:
			expression = "unknown"
		}
		result = append(result, expression)
	}
	return strings.Join(result, " | ")
}

func customerOperationObjectType(schema map[string]any, rootName string, refs map[string]string, depth int) string {
	properties, _ := schema["properties"].(map[string]any)
	required := map[string]bool{}
	if names, ok := schema["required"].([]any); ok {
		for _, name := range names {
			if name, ok := name.(string); ok {
				required[name] = true
			}
		}
	}
	keys := make([]string, 0, len(properties))
	for name := range properties {
		keys = append(keys, name)
	}
	missingRequired := make([]string, 0)
	for name := range required {
		if _, exists := properties[name]; !exists {
			missingRequired = append(missingRequired, name)
			keys = append(keys, name)
		}
	}
	sort.Strings(keys)
	sort.Strings(missingRequired)
	additional, hasAdditional := schema["additionalProperties"]
	closed := hasAdditional && additional == false
	if closed && len(missingRequired) > 0 {
		return "never"
	}
	if len(keys) == 0 {
		if closed {
			return "Record<string, never>"
		}
		return "Record<string, unknown>"
	}
	lines := []string{"{"}
	indent := strings.Repeat("  ", depth+1)
	for _, name := range keys {
		optional := ""
		if !required[name] {
			optional = "?"
		}
		childSchema, exists := properties[name]
		child := "unknown"
		if exists {
			child = customerOperationSchemaType(childSchema, rootName, refs, depth+1)
		}
		lines = append(lines, indent+strconv.Quote(name)+optional+": "+child+";")
	}
	if !closed {
		lines = append(lines, indent+"[key: string]: unknown;")
	}
	lines = append(lines, strings.Repeat("  ", depth)+"}")
	return strings.Join(lines, "\n")
}

func customerOperationArrayType(schema map[string]any, rootName string, refs map[string]string, depth int) string {
	if prefix, ok := schema["prefixItems"].([]any); ok {
		items := make([]string, 0, len(prefix)+1)
		for _, child := range prefix {
			items = append(items, customerOperationSchemaType(child, rootName, refs, depth+1))
		}
		if additional, exists := schema["items"]; !exists || additional != false {
			tail := "unknown"
			if exists {
				tail = customerOperationSchemaType(additional, rootName, refs, depth+1)
			}
			items = append(items, tail)
		}
		if len(items) == 0 {
			return "never[]"
		}
		return parenthesizeCustomerOperationUnion(strings.Join(items, " | ")) + "[]"
	}
	itemType := "unknown"
	if item, exists := schema["items"]; exists {
		itemType = customerOperationSchemaType(item, rootName, refs, depth+1)
	}
	return parenthesizeCustomerOperationUnion(itemType) + "[]"
}

func customerOperationEnumType(values []any) string {
	if len(values) == 0 {
		return "never"
	}
	items := make([]string, 0, len(values))
	for _, value := range values {
		items = append(items, customerOperationLiteralType(value))
	}
	return strings.Join(items, " | ")
}

func customerOperationLiteralType(value any) string {
	switch value.(type) {
	case map[string]any, []any:
		// TypeScript has no exact object/array literal type. Keep the projection
		// sound rather than emitting invalid type syntax or overclaiming exactness.
		return "unknown"
	}
	encoded, err := json.Marshal(value)
	if err != nil {
		return "unknown"
	}
	return string(encoded)
}

func writeCustomerOperationTypes(dir, name string, contents []byte) error {
	parts, err := customerOperationTypesOutputParts(name)
	if err != nil {
		return err
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return fmt.Errorf("open source directory: %w", err)
	}
	defer func() { _ = root.Close() }()
	for i := 0; i < len(parts)-1; i++ {
		current := filepath.Join(parts[:i+1]...)
		info, err := root.Lstat(current)
		if err != nil {
			return fmt.Errorf("inspect output directory: %w", err)
		}
		if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
			return fmt.Errorf("output path must use existing regular directories, without symlinks")
		}
	}
	if info, err := root.Lstat(name); err == nil {
		if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
			return fmt.Errorf("existing output must be a regular generated file")
		}
		previous, err := readCustomerOperationSourceFile(root, name, 8<<20)
		if err != nil {
			return fmt.Errorf("read existing output: %w", err)
		}
		if !strings.HasPrefix(string(previous), customerOperationTypesMarker+"\n") {
			return fmt.Errorf("refusing to replace %q because it is not marked as generated", name)
		}
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("inspect existing output: %w", err)
	}
	if len(contents) > 8<<20 {
		return fmt.Errorf("generated declarations exceed 8 MiB")
	}
	var nonce [8]byte
	if _, err := rand.Read(nonce[:]); err != nil {
		return fmt.Errorf("create output temporary name: %w", err)
	}
	temporary := filepath.Join(filepath.Dir(name), "."+filepath.Base(name)+"."+hex.EncodeToString(nonce[:])+".tmp")
	file, err := root.OpenFile(temporary, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return fmt.Errorf("create generated output: %w", err)
	}
	defer func() { _ = root.Remove(temporary) }()
	_, writeErr := file.Write(contents)
	syncErr := file.Sync()
	closeErr := file.Close()
	if writeErr != nil || syncErr != nil || closeErr != nil {
		return errorsJoin(writeErr, syncErr, closeErr)
	}
	if err := root.Rename(temporary, name); err != nil {
		return fmt.Errorf("replace generated output: %w", err)
	}
	return nil
}

func checkCustomerOperationTypes(dir, name string, expected []byte) (string, error) {
	parts, err := customerOperationTypesOutputParts(name)
	if err != nil {
		return "", err
	}
	if len(expected) > 8<<20 {
		return "", fmt.Errorf("generated declarations exceed 8 MiB")
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return "", fmt.Errorf("open source directory: %w", err)
	}
	defer func() { _ = root.Close() }()
	for i := 0; i < len(parts)-1; i++ {
		current := filepath.Join(parts[:i+1]...)
		info, err := root.Lstat(current)
		if errors.Is(err, os.ErrNotExist) {
			return "missing", nil
		}
		if err != nil {
			return "", fmt.Errorf("inspect output directory: %w", err)
		}
		if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
			return "", fmt.Errorf("output path must use existing regular directories, without symlinks")
		}
	}
	info, err := root.Lstat(name)
	if errors.Is(err, os.ErrNotExist) {
		return "missing", nil
	}
	if err != nil {
		return "", fmt.Errorf("inspect existing output: %w", err)
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
		return "", fmt.Errorf("existing output must be a regular generated file")
	}
	previous, err := readCustomerOperationSourceFile(root, name, 8<<20)
	if err != nil {
		return "", fmt.Errorf("read existing output: %w", err)
	}
	if !bytes.HasPrefix(previous, []byte(customerOperationTypesMarker+"\n")) {
		return "", fmt.Errorf("refusing to check %q because it is not marked as generated", name)
	}
	if !bytes.Equal(previous, expected) {
		return "stale", nil
	}
	return "current", nil
}

func customerOperationTypesOutputParts(name string) ([]string, error) {
	if name == "" || !filepath.IsLocal(name) || filepath.Clean(name) != name || strings.ContainsAny(name, "\\\x00\r\n") || (filepath.Ext(name) != ".ts" && !strings.HasSuffix(name, ".d.ts")) {
		return nil, fmt.Errorf("--output must be a source-local .ts or .d.ts file")
	}
	return strings.Split(name, string(filepath.Separator)), nil
}

func errorsJoin(errs ...error) error {
	filtered := make([]error, 0, len(errs))
	for _, err := range errs {
		if err != nil {
			filtered = append(filtered, err)
		}
	}
	if len(filtered) == 0 {
		return nil
	}
	return fmt.Errorf("write generated declarations: %w", errors.Join(filtered...))
}
