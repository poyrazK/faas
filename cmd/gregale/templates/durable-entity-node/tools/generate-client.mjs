// Declarative generation: reads metadata, never imports customer modules.
import {readFile, writeFile, lstat} from 'node:fs/promises';
import {resolve, relative, isAbsolute} from 'node:path';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const metadata = await readFile(resolve(root, 'gregale.entities.json'));
if (metadata.length > 65536) throw new TypeError('entity metadata is too large');
const project = JSON.parse(metadata.toString('utf8'));
if (project.version !== 1 || !Array.isArray(project.handlers) || project.handlers.length < 1 || project.handlers.length > 64) throw new TypeError('invalid entity project');
const lines = ['// Generated by npm run generate:client. Do not edit.', "import {durableEntityClient} from '@gregale/sdk-node/durable-entities/client';"];
const names = new Set(); const namespaces = new Set();
for (const [index, handler] of project.handlers.entries()) {
  const client = handler.client;
  if (!client || !/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(client.export) || !/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(handler.export) || names.has(handler.export) || namespaces.has(handler.namespace) || typeof handler.namespace !== 'string' || !handler.namespace.trim()) throw new TypeError('declare unique namespaces, factory exports and client contracts');
  const module = client.module;
  if (typeof module !== 'string' || isAbsolute(module) || module.includes('\\') || module.split('/').some(part => !part || part === '.' || part === '..') || !/\.(?:mjs|js)$/u.test(module)) throw new TypeError('invalid client module path');
  let path = root;
  for (const part of module.split('/')) {path = resolve(path, part); const stat = await lstat(path); if (stat.isSymbolicLink()) throw new TypeError('client module symlinks are unsupported');}
  if (!(await lstat(path)).isFile() || relative(root, path).startsWith('../')) throw new TypeError('client module must be a regular project file');
  names.add(handler.export); namespaces.add(handler.namespace);
  const alias = `contract${index}`;
  lines.push(`import {${client.export} as ${alias}} from ${JSON.stringify('./'+module)};`);
  lines.push(`/** @param {Omit<import('@gregale/sdk-node').DurableEntityHandleScope, 'namespace'>} scope */`);
  lines.push(`function factory${index}(scope) { if (${alias}.namespace !== ${JSON.stringify(handler.namespace)}) throw new TypeError('client namespace differs from declaration'); return durableEntityClient(${alias}, scope); }`);
  lines.push(`export {factory${index} as ${handler.export}};`);
}
const target = resolve(root, 'client.mjs');
try {if ((await lstat(target)).isSymbolicLink()) throw new TypeError('refuse symlink client output');} catch(error) {if (error.code !== 'ENOENT') throw error;}
const output = lines.join('\n')+'\n';
if (process.argv.includes('--check')) {if (await readFile(target, 'utf8') !== output) throw new TypeError('client.mjs is stale; run npm run generate:client');}
else await writeFile(target, output);
