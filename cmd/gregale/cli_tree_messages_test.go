package main_test

import (
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// cliTreeMessageExempt are the files that name earlier names on purpose
// (the tree's table, its hint, earlier-name help and the reference's note
// on them) and tests, whose expectations follow what the CLI prints.
func cliTreeMessageExempt(name string) bool {
	return strings.HasPrefix(name, "cli_tree") || strings.HasPrefix(name, "cli_help_groups") ||
		name == "man_markdown.go" || strings.HasSuffix(name, "_test.go")
}

// spellGoLiterals rewrites the `gregale …` commands inside the string
// literals of a Go source file in the tree's names. The words it rewrites
// are plain lowercase text, spelled the same in source as in the value.
func spellGoLiterals(t *testing.T, path string) (string, int) {
	t.Helper()
	src, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	file, err := parser.ParseFile(token.NewFileSet(), path, src, parser.SkipObjectResolution)
	if err != nil {
		t.Fatal(err)
	}
	type span struct {
		start, end int
		afterCLI   bool // the literal continues `recoveryCLI() + "…"`
	}
	var literals []span
	ast.Inspect(file, func(node ast.Node) bool {
		if call, ok := node.(*ast.BinaryExpr); ok && call.Op == token.ADD {
			if lit, ok := call.Y.(*ast.BasicLit); ok && lit.Kind == token.STRING && isRecoveryCLICall(call.X) {
				literals = append(literals, span{int(lit.Pos()) - 1, int(lit.End()) - 1, true})
			}
		}
		if lit, ok := node.(*ast.BasicLit); ok && lit.Kind == token.STRING && strings.Contains(lit.Value, "gregale ") {
			literals = append(literals, span{int(lit.Pos()) - 1, int(lit.End()) - 1, false})
		}
		return true
	})
	sort.Slice(literals, func(i, j int) bool { return literals[i].start > literals[j].start })
	out, changed := string(src), 0
	for _, lit := range literals {
		before := out[lit.start:lit.end]
		if strings.Contains(before, "Code generated by") {
			continue // generated files are recognized by this marker; it never changes
		}
		after := spellDocLine(before, true)
		if lit.afterCLI {
			// `" jobs list"` reads as `gregale jobs list`.
			quote := before[:1]
			spelled := spellDocLine(quote+"gregale"+before[1:], true)
			after = quote + strings.TrimPrefix(spelled, quote+"gregale")
		}
		if after != before {
			out = out[:lit.start] + after + out[lit.end:]
			changed++
		}
	}
	return out, changed
}

// isRecoveryCLICall reports `recoveryCLI()`, the binary name next steps
// begin with.
func isRecoveryCLICall(expr ast.Expr) bool {
	call, ok := expr.(*ast.CallExpr)
	if !ok {
		return false
	}
	ident, ok := call.Fun.(*ast.Ident)
	return ok && ident.Name == "recoveryCLI" && len(call.Args) == 0
}

// The CLI's own messages (usage lines, next steps, examples and hints)
// spell commands in the command tree's names (ADR-20261026145832 step 5).
// Rewrite them with GREGALE_UPDATE_CLI_TREE_MESSAGES=1.
func TestCliMessagesSpellCommandsInTheTree(t *testing.T) {
	enableEveryCLIFeature(t)
	dir, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	// The CLI and the management MCP server it serves (`gregale mcp
	// serve`); server packages keep today's names while a CLI a release
	// behind may run their advice (docs/release-compatibility.md).
	var paths []string
	for _, pattern := range []string{"*.go", "../../pkg/mcpmanagement/*.go"} {
		matches, err := filepath.Glob(filepath.Join(dir, pattern))
		if err != nil {
			t.Fatal(err)
		}
		paths = append(paths, matches...)
	}
	t.Chdir(t.TempDir()) // no linked checkout may resolve an app
	// =1 rewrites the CLI's messages; =tests also rewrites the expectations
	// tests hold for them, once, after a rename.
	mode := os.Getenv("GREGALE_UPDATE_CLI_TREE_MESSAGES")
	update := mode == "1" || mode == "tests"
	total := 0
	for _, path := range paths {
		name := filepath.Base(path)
		if cliTreeMessageExempt(name) && (mode != "tests" || !strings.HasSuffix(name, "_test.go") || strings.HasPrefix(name, "cli_tree") || strings.HasPrefix(name, "cli_help_groups")) {
			continue
		}
		after, changed := spellGoLiterals(t, path)
		if changed == 0 {
			continue
		}
		total += changed
		if update {
			if err := os.WriteFile(path, []byte(after), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		t.Errorf("%s: %d messages spell commands by today's names; rewrite with GREGALE_UPDATE_CLI_TREE_MESSAGES=1", filepath.Base(path), changed)
	}
	if update {
		t.Logf("rewrote %d literals", total)
	}
}
