// commands/completion_powershell.go — Tier A8 / ADR-083.
//
// `gregale completion powershell` emits a PowerShell snippet that
// registers an argument completer via Register-ArgumentCompleter.
// The completer reads the cliCommands manifest at emit time
// (hard-coded into the snippet) and walks $words to figure out
// which position the cursor is at, then offers the right set.
//
// PowerShell's completion model is the most different of the four
// — there's no per-shell flag value parsing built in. The completer
// must parse $wordToComplete manually. The snippet below implements
// that as a single switch on the command name; the verb/flag tables
// are inline string literals.

package main

import (
	"fmt"
	"io"
	"strings"
)

func cmdCompletionPowershell() int {
	renderPowershellCompletion(osStdout)
	return 0
}

func renderPowershellCompletion(w io.Writer) {
	renderPowershellHeader(w)
	for _, c := range completionCliCommands() {
		renderPowershellCommand(w, c)
	}
	renderPowershellFooter(w)
}

