func fishCompletionPathCondition(command cliCommand, path []string) string {
	conditions := []string{fmt.Sprintf("test \"$words[2]\" = %q", command.Name)}
	for i, token := range path {
		conditions = append(conditions, fmt.Sprintf("test \"$words[%d]\" = %q", i+3, token))
	}
	return strings.Join(conditions, "; and ")
}

func fishCompletionPositionCondition(command cliCommand, position cliCompletionPosition) string {
	conditions := []string{fishCompletionPathCondition(command, position.Path)}
	contextCount := len(position.Path) + 1 + position.Position
	conditions = append(conditions, fmt.Sprintf("test $position -eq %d", contextCount))
	return strings.Join(conditions, "; and ")
}

func fishAppSlugPositionCondition(position cliAppSlugCompletionPosition) string {
	conditions := []string{fmt.Sprintf("test \"$words[2]\" = %q", position.Command)}
	for i, token := range position.Path {
		conditions = append(conditions, fmt.Sprintf("test \"$words[%d]\" = %q", position.PathOffsets[i]+2, token))
	}
	for _, offset := range position.RequiredPositionOffsets {
		conditions = append(conditions, fmt.Sprintf("test -n \"$words[%d]\"", offset+2))
	}
	conditions = append(conditions, fmt.Sprintf("test $position -eq %d", position.WordOffset+1))
	return strings.Join(conditions, "; and ")
}

func renderFishAppSlugPosition(w io.Writer) {
	_, _ = fmt.Fprintln(w, "function __gregale_app_slug_position")
	_, _ = fmt.Fprintln(w, "  set -l words (__gregale_context_words)")
	_, _ = fmt.Fprintln(w, "  set -l position (count $words)")
	for _, position := range appSlugCompletionPositions() {
		_, _ = fmt.Fprintf(w, "  if %s\n", fishAppSlugPositionCondition(position))
		_, _ = fmt.Fprintln(w, "    return 0")
		_, _ = fmt.Fprintln(w, "  end")
	}
	_, _ = fmt.Fprintln(w, "  return 1")
	_, _ = fmt.Fprintln(w, "end")
}

func renderFishEnvironmentProjectLookup(w io.Writer) {
	command := projectCompletionCommand()
	_, _ = fmt.Fprintln(w, "function __gregale_environment_project")
	_, _ = fmt.Fprintln(w, "  set -l words (__gregale_context_words)")
	for _, context := range projectCompletionContexts() {
		projectIndex := 2 + len(context.Path) + context.Position
		_, _ = fmt.Fprintf(w, "  if %s; and test -n \"$words[%d]\"\n", fishCompletionPathCondition(command, context.Path), projectIndex)
		_, _ = fmt.Fprintf(w, "    printf '%%s\\n' $words[%d]\n", projectIndex)
		_, _ = fmt.Fprintln(w, "    return 0")
		_, _ = fmt.Fprintln(w, "  end")
	}
	_, _ = fmt.Fprintln(w, "  return 1")
	_, _ = fmt.Fprintln(w, "end")
}

