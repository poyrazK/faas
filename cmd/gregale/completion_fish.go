func renderFishCommand(w io.Writer, c cliCommand) {
	subcommandWord := c.completionSubcommandWord()
	// Top-level command (when no subcommand matches).
	if len(c.Subcommands) == 0 {
		_, _ = fmt.Fprintf(w, "complete -c gregale -f -n \"__fish_use_subcommand\" -a %q -d %q\n",
			c.Name, c.Short)
	} else {
		verbList := make([]string, 0, len(c.Subcommands))
		for _, s := range c.Subcommands {
			verbList = append(verbList, s.completionSpellings()...)
		}
		_, _ = fmt.Fprintf(w, "complete -c gregale -f -n \"__fish_use_subcommand\" -a %q -d %q\n",
			c.Name, c.Short)
		// Subcommand completion.
		_, _ = fmt.Fprintf(w, "complete -c gregale -f -n \"__fish_seen_subcommand_from %s; and test (count (commandline -opc)) -eq %d\" -a \"%s\"\n",
			c.Name, subcommandWord, strings.Join(verbList, " "))
		for _, parent := range c.Subcommands {
			if len(parent.Subcommands) == 0 && len(parent.Flags) > 0 {
				flagCount := subcommandWord + 1
				if parent.FlagsAfterPositionals {
					flagCount += len(parent.Positionals)
				}
				condition := fmt.Sprintf("__fish_seen_subcommand_from %s; and %s; and test (count (commandline -opc)) -ge %d", c.Name, fishSeenSubcommand(parent), flagCount)
				for _, f := range parent.Flags {
					renderFishFlag(w, condition, f)
				}
			}
			if len(parent.Subcommands) == 0 {
				continue
			}
			childWord := subcommandWord + 1
			if parent.SubcommandsAfterPositionals {
				childWord += len(parent.Positionals)
			}
			childWords := make([]string, 0, len(parent.Subcommands))
			for _, child := range parent.Subcommands {
				childWords = append(childWords, child.completionSpellings()...)
			}
			_, _ = fmt.Fprintf(w, "complete -c gregale -f -n \"__fish_seen_subcommand_from %s; and %s; and test (count (commandline -opc)) -eq %d\" -a \"%s\"\n",
				c.Name, fishSeenSubcommand(parent), childWord, strings.Join(childWords, " "))
			for _, child := range parent.Subcommands {
				leafFlagsCount := childWord + 1
				if child.FlagsAfterPositionals {
					leafFlagsCount += len(child.Positionals)
				}
				for _, f := range child.Flags {
					condition := fmt.Sprintf("__fish_seen_subcommand_from %s; and %s; and %s; and test (count (commandline -opc)) -ge %d", c.Name, fishSeenSubcommand(parent), fishSeenSubcommand(child), leafFlagsCount)
					renderFishFlag(w, condition, f)
				}
			}
		}
	}
	// Closed-set positional (plan).
	if len(c.ClosedSet) > 0 {
		_, _ = fmt.Fprintf(w, "complete -c gregale -f -n \"__fish_seen_subcommand_from %s\" -a \"%s\"\n",
			c.Name, strings.Join(c.ClosedSet, " "))
	}
	// Flags.
	for _, f := range c.Flags {
		renderFishFlag(w, fmt.Sprintf("__fish_seen_subcommand_from %s", c.Name), f)
	}
}

func fishSeenSubcommand(sub cliSub) string {
	return "__fish_seen_subcommand_from " + strings.Join(sub.completionSpellings(), " ")
}

func renderFishFlag(w io.Writer, condition string, f cliFlag) {
	option := "-l " + f.Name
	if f.ShortName != "" {
		if f.ShortName == f.Name {
			option = "-s " + f.ShortName
		} else {
			option += " -s " + f.ShortName
		}
	}
	arguments := []string{option}
	if cliFlagTakesValue(f) {
		arguments = append(arguments, "-r")
	}
	if len(f.ClosedSet) > 0 {
		arguments = append(arguments, "-a", fmt.Sprintf("%q", strings.Join(f.ClosedSet, " ")))
	}
	if cliFlagUsesEnvironmentValues(f) {
		arguments = append(arguments, "-a", `"(__gregale_context_environment_slugs)"`)
	}
	if cliFlagUsesFilePathValues(f) {
		// -F restores path suggestions after -f has disabled them for
		// the other Gregale options.
		arguments = append(arguments, "-F")
	}
	_, _ = fmt.Fprintf(w, "complete -c gregale -f -n %q %s -d %q\n", condition, strings.Join(arguments, " "), f.Short)
}

func renderFishFooter(w io.Writer) {
	// No-op: fish has no main completion function.
}
