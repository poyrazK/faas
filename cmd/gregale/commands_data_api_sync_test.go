const dataAPISyncTestTypes = "// Generated by gregale data-api types. Do not edit.\n// Schema fingerprint: " +
	"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\nexport type Database = { priority: number }\n"

func dataAPISyncTestConfig(t *testing.T) (string, dataAPISyncConfig) {
	t.Helper()
	t.Setenv("GREGALE_DATA_API_SYNC_HELPER", "1")
	t.Setenv("GREGALE_DATA_API_ACCESS_TOKEN", "application.test.token")
	// Race-instrumented helper processes otherwise pause for one second on exit.
	t.Setenv("GORACE", "exit_sleep_ms=0")
	root := filepath.Join(t.TempDir(), "project with spaces")
	for _, dir := range []string{"schema", "web"} {
		if err := os.MkdirAll(filepath.Join(root, dir), 0700); err != nil {
			t.Fatal(err)
		}
	}
	executable, err := os.Executable()
	if err != nil {
		t.Fatal(err)
	}
	args := []string{executable, "-test.run=^TestDataAPISyncCommandHelper$", "--"}
	config := dataAPISyncConfig{
		Output:      "web/database.types.ts",
		Migrate:     dataAPISyncCommand{Command: append(append([]string{}, args...), "migrate", `literal spaces $();"`), Directory: "schema"},
		Permissions: &dataAPISyncCommand{Command: append(append([]string{}, args...), "permissions"), Directory: "schema"},
		Check:       dataAPISyncCommand{Command: append(append([]string{}, args...), "check"), Directory: "web"},
	}
	path := filepath.Join(root, "data-api.json")
	writeDataAPISyncTestConfig(t, path, config)
	if err := os.WriteFile(filepath.Join(root, config.Output), []byte("original types"), 0600); err != nil {
		t.Fatal(err)
	}
	return path, config
}

func writeDataAPISyncTestConfig(t *testing.T, path string, config any) {
	t.Helper()
	content, err := json.Marshal(config)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, content, 0600); err != nil {
		t.Fatal(err)
	}
}

// A real executable fixture proves directory and argv handling without relying
// on shell quoting or invoking customer deployment tools in unit tests.
func TestDataAPISyncCommandHelper(t *testing.T) {
	if os.Getenv("GREGALE_DATA_API_SYNC_HELPER") != "1" {
		return
	}
	index := 0
	for index < len(os.Args) && os.Args[index] != "--" {
		index++
	}
	args := os.Args[index+1:]
	if len(args) == 0 {
		os.Exit(3)
	}
	_, _ = fmt.Fprintln(os.Stdout, "local command stdout")
	_, _ = fmt.Fprintln(os.Stderr, "local command stderr")
	switch args[0] {
	case "migrate":
		cwd, _ := os.Getwd()
		content, _ := json.Marshal(map[string]any{"cwd": cwd, "args": args[1:]})
		if os.WriteFile("migration.json", content, 0600) != nil {
			os.Exit(4)
		}
		if os.Getenv("GREGALE_DATA_API_SYNC_MIGRATION_FAIL") == "1" {
			os.Exit(2)
		}
	case "permissions":
		if _, err := os.Stat("migration.json"); err != nil {
			os.Exit(10)
		}
		if os.WriteFile("permissions-ran", nil, 0600) != nil {
			os.Exit(11)
		}
		if os.Getenv("GREGALE_DATA_API_SYNC_PERMISSIONS_FAIL") == "1" {
			os.Exit(2)
		}
	case "check":
		content, err := os.ReadFile("database.types.ts")
		if err != nil || string(content) != dataAPISyncTestTypes {
			os.Exit(5)
		}
		if os.WriteFile("check-ran", nil, 0600) != nil {
			os.Exit(6)
		}
		if os.Getenv("GREGALE_DATA_API_SYNC_CHECK_FAIL") == "1" {
			os.Exit(2)
		}
	case "wait":
		time.Sleep(30 * time.Second)
	case "wait-child":
		executable, _ := os.Executable()
		child := exec.Command(executable, "-test.run=^TestDataAPISyncCommandHelper$", "--", "wait")
		child.Stdout, child.Stderr = os.Stdout, os.Stderr
		if child.Start() != nil {
			os.Exit(8)
		}
		if os.WriteFile("child.pid", []byte(fmt.Sprint(child.Process.Pid)), 0600) != nil {
			_ = child.Process.Kill()
			os.Exit(9)
		}
		_ = child.Wait()
	default:
		os.Exit(7)
	}
	os.Exit(0)
}

type dataAPISyncTestServer struct {
	restarts atomic.Int32
	tasks    atomic.Int32
	health   atomic.Int32
}

func newDataAPISyncTestServer(t *testing.T, root, failure string) *dataAPISyncTestServer {
	t.Helper()
	fixture := &dataAPISyncTestServer{}
	health := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path == "/__gregale/schema" {
			if r.Header.Get("Authorization") != "Bearer application.test.token" || fixture.tasks.Load() != 1 {
				t.Error("contract check must use application auth after type export")
			}
			if failure == "contract-auth" {
				w.WriteHeader(http.StatusUnauthorized)
				return
			}
			fingerprint := strings.Repeat("a", 64)
			if failure == "contract-stale" {
				fingerprint = strings.Repeat("b", 64)
			}
			writeJSONTest(w, map[string]any{"version": 1, "ready": true, "fingerprint": fingerprint})
			return
		}
		fixture.health.Add(1)
		if fixture.restarts.Load() != 1 || r.Header.Get("Authorization") != "" {
			t.Error("health preceded the refresh or leaked account credentials")
		}
		if failure == "health" {
			w.WriteHeader(http.StatusForbidden)
			return
		}
		writeJSONTest(w, map[string]bool{"ready": true})
	}))
	t.Cleanup(health.Close)
	transport := http.DefaultTransport
	http.DefaultTransport = health.Client().Transport
	t.Cleanup(func() { http.DefaultTransport = transport })
	management := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("Authorization") != "Bearer owner-test-token" {
			t.Error("missing management authentication")
		}
		switch r.Method + " " + r.URL.Path {
		case "GET /v1/apps/notes":
			writeJSONTest(w, api.AppResponse{ID: "app", Slug: "notes", URL: health.URL})
		case "POST /v1/apps/notes/restart":
			if _, err := os.Stat(filepath.Join(root, "schema/migration.json")); err != nil || r.URL.RawQuery != "fresh=true" {
				t.Error("refresh must follow migration and use a fresh restart")
			}
			if _, err := os.Stat(filepath.Join(root, "schema/permissions-ran")); err != nil && failure != "legacy" {
				t.Error("refresh must follow permission setup")
			}
			fixture.restarts.Add(1)
			writeJSONTest(w, api.AppRestartResponse{WakeID: "wake-1"})
		case "GET /v1/apps/notes/runtime-config-restarts/wake-1":
			status := "completed"
			if failure == "restart" {
				status = "failed"
			}
			writeJSONTest(w, api.RuntimeConfigRestartStatusResponse{WakeID: "wake-1", Status: status})
		case "POST /v1/apps/notes/tasks":
			fixture.tasks.Add(1)
			if fixture.health.Load() == 0 {
				t.Error("type export preceded readiness")
			}
			var request api.CreateAppTaskRequest
			if json.NewDecoder(r.Body).Decode(&request) != nil || strings.Join(request.Command, " ") != "node /app/types.mjs" || request.TimeoutSeconds != 60 || request.MaxOutputBytes != api.AppTaskDefaultMaxOutputBytes {
				t.Error("type export did not use the bounded private runtime task")
			}
			task := api.AppTaskResponse{ID: "task-1", DeploymentID: "live-1", Status: api.AppTaskStatusSucceeded, StdoutTail: dataAPISyncTestTypes}
			switch failure {
			case "types":
				task.Status = api.AppTaskStatusFailed
			case "truncated":
				task.OutputTruncated = true
			case "type-timeout":
				task.Status = api.AppTaskStatusQueued
			}
			writeJSONTest(w, task)
		case "GET /v1/apps/notes/tasks/task-1":
			writeJSONTest(w, api.AppTaskResponse{ID: "task-1", DeploymentID: "live-1", Status: api.AppTaskStatusQueued})
		default:
			t.Errorf("unexpected management request: %s %s", r.Method, r.URL.Path)
			w.WriteHeader(http.StatusNotFound)
		}
	}))
	t.Cleanup(management.Close)
	t.Setenv("FAAS_API", management.URL)
	t.Setenv("FAAS_TOKEN", "owner-test-token")
	return fixture
}

