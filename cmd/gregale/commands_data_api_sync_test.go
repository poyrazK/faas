func TestDataAPISyncJourney(t *testing.T) {
	for _, flagsFirst := range []bool{false, true} {
		t.Run(fmt.Sprint(flagsFirst), func(t *testing.T) {
			resetJSONOut(t)
			path, config := dataAPISyncTestConfig(t)
			if flagsFirst {
				config.AccessTokenEnv = "CUSTOM_APPLICATION_JWT"
				t.Setenv("CUSTOM_APPLICATION_JWT", "application.test.token")
				t.Setenv("GREGALE_DATA_API_ACCESS_TOKEN", "")
				writeDataAPISyncTestConfig(t, path, config)
			}
			root := filepath.Dir(path)
			fixture := newDataAPISyncTestServer(t, root, "")
			// Paths must resolve from the config, independent of the calling cwd.
			t.Chdir(t.TempDir())
			out, stderr, restore := swapIO(t)
			defer restore()
			args := []string{"notes", "--config", path}
			if flagsFirst {
				args = []string{"--config", path, "notes"}
			}
			if code := run(append([]string{"--json", "data-api", "sync"}, args...)); code != 0 {
				t.Fatalf("sync exit=%d: %s", code, stderr())
			}
			decoder := json.NewDecoder(out)
			var receipt dataAPISyncReceipt
			if err := decoder.Decode(&receipt); err != nil || receipt.Status != "completed" || !receipt.ContractVerified || receipt.WakeID != "wake-1" || receipt.TaskID != "task-1" || receipt.DeploymentID != "live-1" || receipt.Fingerprint != strings.Repeat("a", 64) {
				t.Fatalf("receipt=%+v error=%v", receipt, err)
			}
			if err := decoder.Decode(new(any)); !errors.Is(err, io.EOF) {
				t.Fatalf("stdout contains more than one receipt: %v", err)
			}
			content, err := os.ReadFile(filepath.Join(root, "schema/migration.json"))
			var migrated struct {
				CWD  string   `json:"cwd"`
				Args []string `json:"args"`
			}
			if err != nil || json.Unmarshal(content, &migrated) != nil || migrated.CWD != filepath.Join(root, "schema") || len(migrated.Args) != 1 || migrated.Args[0] != `literal spaces $();"` {
				t.Fatalf("migration argv or cwd changed: %s, %v", content, err)
			}
			if _, err := os.Stat(filepath.Join(root, "web/check-ran")); err != nil || fixture.restarts.Load() != 1 || fixture.tasks.Load() != 1 || fixture.health.Load() != 1 {
				t.Fatal("workflow did not complete exactly once")
			}
			if !strings.Contains(stderr(), "local command stdout") || !strings.Contains(stderr(), "local command stderr") {
				t.Fatal("local diagnostics were not routed to stderr")
			}
		})
	}
}

func TestDataAPISyncStopsAtFailedStep(t *testing.T) {
	for _, failure := range []string{"migration", "permissions", "restart", "health", "types", "truncated", "check", "contract-stale", "contract-auth", "type-timeout"} {
		t.Run(failure, func(t *testing.T) {
			resetJSONOut(t)
			path, _ := dataAPISyncTestConfig(t)
			root := filepath.Dir(path)
			t.Setenv("GREGALE_DATA_API_SYNC_MIGRATION_FAIL", "0")
			t.Setenv("GREGALE_DATA_API_SYNC_PERMISSIONS_FAIL", "0")
			t.Setenv("GREGALE_DATA_API_SYNC_CHECK_FAIL", "0")
			if failure == "migration" {
				t.Setenv("GREGALE_DATA_API_SYNC_MIGRATION_FAIL", "1")
			}
			if failure == "permissions" {
				t.Setenv("GREGALE_DATA_API_SYNC_PERMISSIONS_FAIL", "1")
			}
			if failure == "check" {
				t.Setenv("GREGALE_DATA_API_SYNC_CHECK_FAIL", "1")
			}
			fixture := newDataAPISyncTestServer(t, root, failure)
			out, stderr, restore := swapIO(t)
			defer restore()
			args := []string{"--json", "data-api", "sync", "notes", "--config", path}
			if failure == "type-timeout" {
				args = append(args, "--timeout", "3s")
			}
			if code := run(args); code == 0 || out.Len() != 0 {
				t.Fatalf("failed workflow reported success: exit=%d output=%s", code, out.String())
			}
			wantRestarts, wantTasks := int32(1), int32(1)
			if failure == "migration" || failure == "permissions" {
				wantRestarts = 0
			}
			if failure == "migration" || failure == "permissions" || failure == "restart" || failure == "health" {
				wantTasks = 0
			}
			if fixture.restarts.Load() != wantRestarts || fixture.tasks.Load() != wantTasks {
				t.Fatalf("unexpected remote work: restarts=%d tasks=%d; %s", fixture.restarts.Load(), fixture.tasks.Load(), stderr())
			}
			content, _ := os.ReadFile(filepath.Join(root, "web/database.types.ts"))
			want := "original types"
			if failure == "check" {
				want = dataAPISyncTestTypes
			}
			if string(content) != want {
				t.Fatal("invalid generation replaced the file, or a check failure discarded the new contract")
			}
			_, checkErr := os.Stat(filepath.Join(root, "web/check-ran"))
			if (checkErr == nil) != (failure == "check") {
				t.Fatal("client check ran before valid types were written")
			}
			if failure == "type-timeout" && (!strings.Contains(stderr(), "data_api_sync_timeout") || !strings.Contains(stderr(), "wake-1") || !strings.Contains(stderr(), "task-1")) {
				t.Fatalf("timeout lost the phase or remote receipts: %s", stderr())
			}
		})
	}
}

func TestDataAPISyncRejectsInvalidConfigurationBeforeWork(t *testing.T) {
	for _, invalid := range []string{"missing-token", "account-token", "invalid-token", "invalid-token-env", "empty-permissions", "missing-output", "missing-migrate", "missing-check", "missing-executable", "missing-directory", "missing-output-parent", "unknown-field", "multiple-objects", "oversized", "nul-argument"} {
		t.Run(invalid, func(t *testing.T) {
			resetJSONOut(t)
			path, config := dataAPISyncTestConfig(t)
			switch invalid {
			case "account-token":
				t.Setenv("GREGALE_DATA_API_ACCESS_TOKEN", "account-key-sentinel")
			case "missing-token":
				t.Setenv("GREGALE_DATA_API_ACCESS_TOKEN", "")
			case "invalid-token":
				t.Setenv("GREGALE_DATA_API_ACCESS_TOKEN", "secret\nsentinel")
			case "invalid-token-env":
				config.AccessTokenEnv = "bad=name"
			case "empty-permissions":
				config.Permissions.Command = nil
			case "missing-output":
				config.Output = ""
			case "missing-migrate":
				config.Migrate.Command = nil
			case "missing-check":
				config.Check.Command = nil
			case "missing-executable":
				config.Check.Command = []string{filepath.Join(t.TempDir(), "absent")}
			case "missing-directory":
				config.Check.Directory = "absent"
			case "missing-output-parent":
				config.Output = "absent/types.ts"
			case "nul-argument":
				config.Check.Command = append(config.Check.Command, "bad\x00arg")
			}
			writeDataAPISyncTestConfig(t, path, config)
			switch invalid {
			case "unknown-field":
				writeDataAPISyncTestConfig(t, path, map[string]any{"output": "web/types.ts", "typo": true})
			case "multiple-objects":
				_ = os.WriteFile(path, []byte("{} {}"), 0600)
			case "oversized":
				_ = os.WriteFile(path, []byte(strings.Repeat(" ", 64<<10+1)), 0600)
			}
			var calls atomic.Int32
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { calls.Add(1) }))
			defer server.Close()
			t.Setenv("FAAS_API", server.URL)
			t.Setenv("FAAS_TOKEN", "test-token")
			_, _, restore := swapIO(t)
			defer restore()
			if code := cmdDataAPISync([]string{"notes", "--config", path}); code == 0 || calls.Load() != 0 {
				t.Fatal("invalid workflow started network work")
			}
			if _, err := os.Stat(filepath.Join(filepath.Dir(path), "schema/migration.json")); !errors.Is(err, os.ErrNotExist) {
				t.Fatal("invalid workflow ran the migration command")
			}
		})
	}
}

func TestDataAPISyncLocalCommandDeadlineAndCancellation(t *testing.T) {
	path, config := dataAPISyncTestConfig(t)
	config.Migrate.Command[len(config.Migrate.Command)-2] = "wait"
	writeDataAPISyncTestConfig(t, path, config)
	prepared, err := loadDataAPISyncConfig(path)
	if err != nil {
		t.Fatal(err)
	}
	_, _, restore := swapIO(t)
	defer restore()
	ctx, cancel := context.WithTimeout(context.Background(), 100*time.Millisecond)
	defer cancel()
	started := time.Now()
	if err := runDataAPISyncCommand(ctx, prepared.Migrate); !errors.Is(err, context.DeadlineExceeded) || time.Since(started) > 3*time.Second {
		t.Fatalf("local command exceeded the workflow deadline: %v", err)
	}
	cancelled, stop := context.WithCancel(context.Background())
	stop()
	if err := runDataAPISyncCommand(cancelled, prepared.Migrate); !errors.Is(err, context.Canceled) {
		t.Fatalf("cancelled workflow ran a command: %v", err)
	}
}

