import test from 'node:test'
import assert from 'node:assert/strict'
import { execFile, spawn } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { promisify } from 'node:util'
import { setTimeout as delay } from 'node:timers/promises'

const exec = promisify(execFile)
const enabled = process.env.DATA_API_HOSTED_WRITE_SQL_TEST === '1'

// Only a fresh, test-owned local container is used. No customer target is accepted.
test('hosted write inspection reads actual role, column grants, policies and triggers without customer rows', { skip: !enabled, timeout: 120000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), 'gregale-write-inspect-'))
  const name = 'gregale-write-inspect-' + randomBytes(8).toString('hex')
  const password = randomBytes(24).toString('hex')
  const envFile = join(root, 'postgres.env')
  let created = false
  await writeFile(envFile, `POSTGRES_PASSWORD=${password}\n`, { mode: 0o600 })
  t.after(async () => { try { if (created) await exec('docker', ['rm', '--force', '--volumes', name]) } finally { await rm(root, { recursive: true, force: true }) } })
  await exec('docker', ['run', '--detach', '--name', name, '--env-file', envFile, '--publish', '127.0.0.1::5432', 'postgres:16'])
  created = true
  let ready = false
  for (let i = 0; i < 60; i++) {
    try { await exec('docker', ['exec', name, 'pg_isready', '-U', 'postgres']); ready = true; break } catch { await delay(500) }
  }
  assert.equal(ready, true, 'disposable PostgreSQL did not become ready')
  const sql = `CREATE ROLE write_fixture LOGIN PASSWORD '${password}';
CREATE SCHEMA api;
CREATE TABLE api.notes(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, subject text NOT NULL, body text NOT NULL, hidden text);
ALTER TABLE api.notes ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_notes ON api.notes FOR ALL TO write_fixture USING (subject = current_user) WITH CHECK (subject = current_user);
CREATE POLICY public_read_guard ON api.notes AS RESTRICTIVE FOR SELECT TO PUBLIC USING (true);
GRANT USAGE ON SCHEMA api TO write_fixture;
GRANT SELECT(id,subject), INSERT(subject,body), UPDATE(body), DELETE ON api.notes TO write_fixture;
CREATE FUNCTION api.observe_update() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RETURN NEW; END$$;
CREATE TRIGGER observe_update BEFORE UPDATE ON api.notes FOR EACH ROW EXECUTE FUNCTION api.observe_update();
INSERT INTO api.notes(subject,body,hidden) VALUES ('write_fixture','synthetic','private-row-marker');`
  await new Promise((resolve, reject) => {
    const child = spawn('docker', ['exec', '-i', name, 'psql', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1'], { stdio: ['pipe', 'ignore', 'pipe'] })
    let stderr = ''
    child.stderr.on('data', chunk => { stderr += chunk })
    child.on('error', reject)
    child.on('close', code => code === 0 ? resolve() : reject(new Error('fixture setup failed: ' + stderr.replaceAll(password, '[redacted]'))))
    child.stdin.end(sql)
  })
  const port = (await exec('docker', ['port', name, '5432/tcp'])).stdout.trim().match(/:(\d+)$/)?.[1]
  assert.ok(port)
  const script = await readFile(new URL('../../cmd/gregale/data_api_write_inspect_task.js', import.meta.url), 'utf8')
  const env = { ...process.env, DATABASE_URL: `postgresql://write_fixture:${password}@127.0.0.1:${port}/postgres` }
  const output = await exec(process.execPath, ['-e', script, 'notes'], { env, cwd: process.env.DATA_API_RUNTIME_DIR || root, timeout: 30000 })
  const report = JSON.parse(output.stdout)
  assert.equal(report.version, 1)
  assert.equal(report.role.name, 'write_fixture')
  assert.deepEqual(report.transport, { encrypted: false, peer_authorized: null })
  assert.equal(report.role.bypass_rls, false)
  assert.equal(report.relation.name, 'notes')
  assert.equal(report.relation.rls, true)
  assert.equal(report.relation.row_security_active, true)
  assert.equal(report.relation.can_insert, false)
  assert.equal(report.relation.can_update, false)
  assert.equal(report.relation.can_delete, true)
  assert.equal(report.columns.find(column => column.name === 'subject').can_insert, true)
  assert.equal(report.columns.find(column => column.name === 'body').can_update, true)
  assert.equal(report.columns.find(column => column.name === 'hidden').can_select, false)
  assert.ok(report.policies.some(policy => policy.name === 'own_notes' && policy.applies_to_role && policy.command === '*'))
  assert.ok(report.policies.some(policy => policy.name === 'public_read_guard' && policy.applies_to_role && !policy.permissive && policy.command === 'r'))
  assert.ok(report.triggers.some(trigger => trigger.name === 'observe_update' && trigger.enabled === 'O'))
  assert.doesNotMatch(output.stdout + output.stderr, /private-row-marker/)
  await assert.rejects(exec(process.execPath, ['-e', script, 'missing'], { env, cwd: process.env.DATA_API_RUNTIME_DIR || root, timeout: 30000 }), error => error.code !== 0 && !error.stderr.includes(password))
  const count = await exec('docker', ['exec', name, 'psql', '-U', 'postgres', '-d', 'postgres', '-Atc', 'SELECT count(*) FROM api.notes'])
  assert.equal(count.stdout.trim(), '1')
  const extra = Array.from({ length: 125 }, (_, i) => `ADD COLUMN c${i} integer`).join(', ')
  await exec('docker', ['exec', name, 'psql', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-c', `ALTER TABLE api.notes ${extra}`])
  await assert.rejects(exec(process.execPath, ['-e', script, 'notes'], { env, cwd: process.env.DATA_API_RUNTIME_DIR || root, timeout: 30000 }), error => error.code !== 0 && !error.stdout.trim() && !error.stderr.includes(password))
})
