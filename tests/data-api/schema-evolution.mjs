import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

export async function verifySchemaEvolution({ owner, client, refresh, inspect, generate, loginURL, root, command }) {
  const typeFile = join(root, 'client/src/database.types.ts')
  const originalTypes = await readFile(typeFile, 'utf8')
  const contract = async () => generate(await inspect(loginURL, ['api']))
  const originalContract = await contract()
  const created = await client.create('evolution fixture')
  assert.equal(created.error, null)
  const id = created.data.id
  const ownedIds = [id]
  try {
    await owner.query('ALTER TABLE api.notes ADD COLUMN compatibility_label text')
    assert.notEqual(await contract(), originalContract, 'additive_change_not_detected')
    await refresh()
    const read = await client.list().eq('id', id).single()
    assert.equal(read.error, null, 'additive_change_broke_old_read')
    const edited = await client.update(id, read.data.version, { body: 'old client still writes' })
    assert.equal(edited.error, null, 'additive_change_broke_old_write')
    await writeFile(typeFile, await contract())
    await command('npm', ['run', 'typecheck'], { cwd: join(root, 'client'), env: process.env })
    const beforeDefault = await contract()
    await owner.query('ALTER TABLE api.notes ALTER COLUMN priority SET DEFAULT 5')
    assert.equal(await contract(), beforeDefault, 'default values are not encoded in the type contract')
    await refresh()
    const defaults = await client.createMany([{ body: 'new default' }])
    assert.equal(defaults.error, null)
    ownedIds.push(...defaults.data.map(row => row.id))
    assert.equal(defaults.data[0].priority, 5, 'changed_default_not_applied')
    await owner.query("ALTER TABLE api.notes ADD COLUMN compatibility_required text NOT NULL DEFAULT 'legacy'")
    await refresh()
    const compatible = await client.create('required default fixture')
    assert.equal(compatible.error, null, 'required_default_broke_old_insert')
    ownedIds.push(compatible.data.id)
    assert.equal(compatible.data.compatibility_required, 'legacy')
    const withDefault = await contract()
    await owner.query('ALTER TABLE api.notes ALTER COLUMN compatibility_required DROP DEFAULT')
    assert.notEqual(await contract(), withDefault, 'required_default_removal_not_detected')
    await refresh()
    const required = await client.create('missing required field')
    assert.equal(required.error?.code, '23502', 'required_column_break_not_observed')
    await owner.query("ALTER TABLE api.notes ALTER COLUMN compatibility_required SET DEFAULT 'legacy'")
    // Renaming a projected column breaks the old client, after cache refresh too.
    await owner.query('ALTER TABLE api.notes RENAME COLUMN body TO title')
    await refresh()
    const renamed = await client.list()
    assert.equal(renamed.error?.code, '42703', 'rename_silently_compatible')
    const renamedInsert = await client.create('old insert')
    assert.equal(renamedInsert.error?.code, 'PGRST204')
    await writeFile(typeFile, await contract())
    await assert.rejects(command('npm', ['run', 'typecheck'], { cwd: join(root, 'client'), env: process.env }), error => error.code === 'command_failed')
    await owner.query('ALTER TABLE api.notes RENAME COLUMN title TO body')
    // A compatible JSON response can still violate the old compiled TS type.
    await owner.query('ALTER TABLE api.notes ALTER COLUMN priority DROP DEFAULT; ALTER TABLE api.notes ALTER COLUMN priority TYPE text USING priority::text; ALTER TABLE api.notes ALTER COLUMN priority SET DEFAULT \'5\'')
    await refresh()
    const changedType = await client.list().eq('id', id).single()
    assert.equal(changedType.error, null)
    assert.equal(typeof changedType.data.priority, 'string', 'type_change_was_not_observed')
    const textContract = await contract()
    assert.match(textContract, /"priority": string/)
    await writeFile(typeFile, textContract)
    await assert.rejects(command('npm', ['run', 'typecheck'], { cwd: join(root, 'client'), env: process.env }), error => error.code === 'command_failed')
    await owner.query('ALTER TABLE api.notes DROP COLUMN priority')
    await refresh()
    const removed = await client.list()
    assert.equal(removed.error?.code, '42703', 'removed_column_silently_compatible')
    const removedInsert = await client.create('old insert')
    assert.equal(removedInsert.error?.code, 'PGRST204')
    const removedContract = await contract()
    assert.notEqual(removedContract, textContract)
    await writeFile(typeFile, removedContract)
    await assert.rejects(command('npm', ['run', 'typecheck'], { cwd: join(root, 'client'), env: process.env }), error => error.code === 'command_failed')
  } finally {
    await writeFile(typeFile, originalTypes)
    // This is a disposable local database; fixture mutations never reach staging.
    await owner.query('DELETE FROM api.notes WHERE id=ANY($1::integer[])', [ownedIds])
  }
}
