       OR EXISTS (SELECT 1 FROM scenario_object_fixtures WHERE account_id=identity_id AND status NOT IN ('complete','deleted')) THEN
        RETURN true;
    END IF;
    FOR resource_table IN SELECT unnest(ARRAY[
