-- ADR-20261022155043 settles the rehearsal coverage ADR-202610171904 left
-- unreviewed: rehearsal evidence follows its run and its preview app, so it no
-- longer blocks identity erasure. A fixture that still holds a database or a
-- bucket keeps blocking until its cleanup finishes, because erasing its
-- journal would orphan the resource. The body is otherwise the definition
-- from 20261019190114676.

