          WHERE t.id=d.trigger_id AND t.app_id=d.app_id AND t.account_id=d.account_id AND t.kind='queue' AND t.source='queue')))))) THEN
      RETURN true;
    END IF;
    -- Rehearsal evidence follows its run and is erased with the identity; only
