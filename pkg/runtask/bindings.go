package runtask

import (
	"bytes"
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"github.com/onebox-faas/faas/pkg/api"
	"github.com/onebox-faas/faas/pkg/executioncontract"
)

// GenerateBindings generates structural JSON types and a version-pinned SDK
// factory. The SDK still calls the caller's decoder, and the Run service
// validates the full published contracts.
func GenerateBindings(task api.PublishExecutionTaskRequest, language string) ([]byte, error) {
	if !ValidRef(task.Name, task.Version) {
		return nil, fmt.Errorf("a valid task name and version are required")
	}
	if language != "typescript" && language != "python" {
		return nil, fmt.Errorf("use --language typescript or python")
	}
	generator := bindingGenerator{python: language == "python"}
	input, err := generator.contract(task.Definition.InputSchema, "input_schema")
	if err != nil {
		return nil, err
	}
	result, err := generator.contract(task.Definition.ResultSchema, "result_schema")
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	if generator.python {
		fmt.Fprintln(&out, "# Generated by gregale run tasks generate.")
		fmt.Fprint(&out, "import typing\n\nfrom faas_sdk.preview import FaaSClient, Task\n\n")
		out.WriteString(generator.objects.String())
		fmt.Fprintf(&out, "TaskInput: typing.TypeAlias = %s\nTaskResult: typing.TypeAlias = %s\n\n\n", input, result)
		fmt.Fprint(&out, "def bind_task(\n    client: FaaSClient, decode_result: typing.Callable[[object], TaskResult]\n) -> Task[TaskInput, TaskResult]:\n")
		fmt.Fprintf(&out, "    return client.task(%q, %d, decode_result)\n", task.Name, task.Version)
	} else {
		fmt.Fprintln(&out, "// Generated by gregale run tasks generate.")
		fmt.Fprint(&out, "import type { FaaSClient, Task } from '@gregale/sdk-node/preview';\n\n")
		out.WriteString(generator.objects.String())
		fmt.Fprintf(&out, "export type TaskInput = %s;\nexport type TaskResult = %s;\n\n", input, result)
		fmt.Fprint(&out, "export function bindTask(client: FaaSClient, decodeResult: (value: unknown) => TaskResult): Task<TaskInput, TaskResult> {\n")
		fmt.Fprintf(&out, "  return client.task<TaskInput, TaskResult>(%q, %d, decodeResult);\n}\n", task.Name, task.Version)
	}
	return out.Bytes(), nil
}

type bindingGenerator struct {
	python  bool
	objects strings.Builder
	count   int
}

func (g *bindingGenerator) contract(raw json.RawMessage, path string) (string, error) {
	if len(raw) == 0 {
		return g.typeName("unknown"), nil
	}
	if _, err := executioncontract.Compile(raw); err != nil {
		return "", fmt.Errorf("%s must be a bounded local JSON Schema contract", path)
	}
	var schema any
	if err := json.Unmarshal(raw, &schema); err != nil {
		return "", fmt.Errorf("%s: %w", path, err)
	}
	return g.schema(schema, path)
}

func (g *bindingGenerator) typeName(kind string) string {
	if g.python {
		switch kind {
		case "string":
			return "str"
		case "integer":
			return "int"
		case "number":
			return "float"
		case "boolean":
			return "bool"
		case "null":
			return "None"
		case "never":
			return "typing.Never"
		case "unknown":
			return "object"
		}
	}
	if kind == "integer" {
		return "number"
	}
	return kind
}

func (g *bindingGenerator) schema(value any, path string) (string, error) {
	switch schema := value.(type) {
	case bool:
		if schema {
			return g.typeName("unknown"), nil
		}
		return g.typeName("never"), nil
	case map[string]any:
		return g.objectSchema(schema, path)
	default:
		return "", fmt.Errorf("%s must be a JSON Schema object or boolean", path)
	}
}

func (g *bindingGenerator) objectSchema(schema map[string]any, path string) (string, error) {
	for _, key := range sortedBindingKeys(schema) {
		switch key {
		case "type", "properties", "required", "additionalProperties", "items",
			"$schema", "$comment", "title", "description", "default", "examples", "deprecated", "readOnly", "writeOnly",
			"enum", "const", "minLength", "maxLength", "pattern", "format",
			"minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "multipleOf",
			"minItems", "maxItems", "uniqueItems", "minProperties", "maxProperties":
			// Constraints remain on the server, where the full schema is enforced.
		default:
			return "", fmt.Errorf("%s: code generation does not support %q", path, key)
		}
	}
	kinds := []string{"unknown"}
	switch value := schema["type"].(type) {
	case string:
		kinds = []string{value}
	case []any:
		kinds = make([]string, 0, len(value))
		for _, kind := range value {
			kinds = append(kinds, kind.(string)) // validated by Compile
		}
	}
	for _, key := range []string{"properties", "required", "additionalProperties"} {
		if _, present := schema[key]; present && !slices.Contains(kinds, "object") {
			return "", fmt.Errorf("%s: %q requires an explicit object type for code generation", path, key)
		}
	}
	if _, present := schema["items"]; present && !slices.Contains(kinds, "array") {
		return "", fmt.Errorf("%s: items requires an explicit array type for code generation", path)
	}
	var names []string
	for _, kind := range kinds {
		name, err := g.schemaType(schema, kind, path)
		if err != nil {
			return "", err
		}
		if !slices.Contains(names, name) {
			names = append(names, name)
		}
	}
	return strings.Join(names, " | "), nil
}

func (g *bindingGenerator) schemaType(schema map[string]any, kind, path string) (string, error) {
	switch kind {
	case "object":
		return g.objectType(schema, path)
	case "array":
		item := g.typeName("unknown")
		if raw, ok := schema["items"]; ok {
			var err error
			item, err = g.schema(raw, path+".items")
			if err != nil {
				return "", err
			}
		}
		if g.python {
			return "list[" + item + "]", nil
		}
		return "Array<" + item + ">", nil
	default:
		return g.typeName(kind), nil
	}
}

func (g *bindingGenerator) objectType(schema map[string]any, path string) (string, error) {
	properties, _ := schema["properties"].(map[string]any)
	required := make(map[string]bool)
	if keys, ok := schema["required"].([]any); ok {
		for _, value := range keys {
			key := value.(string) // validated by Compile
			if _, present := properties[key]; !present {
				return "", fmt.Errorf("%s: required property %q needs a declared schema", path, key)
			}
			required[key] = true
		}
	}
	additional, present := schema["additionalProperties"]
	if len(properties) == 0 {
		extra := g.typeName("unknown")
		if present {
			var err error
			extra, err = g.schema(additional, path+".additionalProperties")
			if err != nil {
				return "", err
			}
		}
		if g.python {
			return "dict[str, " + extra + "]", nil
		}
		return "Record<string, " + extra + ">", nil
	}
	if _, boolean := additional.(bool); present && !boolean {
		return "", fmt.Errorf("%s: code generation cannot combine fixed properties and a typed additionalProperties schema", path)
	}
	var fields strings.Builder
	for _, key := range sortedBindingKeys(properties) {
		kind, err := g.schema(properties[key], fmt.Sprintf("%s.properties[%q]", path, key))
		if err != nil {
			return "", err
		}
		// JSON string literals are valid in both languages. In particular, JSON
		// escaping avoids Go-only control-character escapes in generated code.
		wireKey, _ := json.Marshal(key)
		if g.python {
			if !required[key] {
				kind = "typing.NotRequired[" + kind + "]"
			}
			fmt.Fprintf(&fields, "        %s: %s,\n", wireKey, kind)
		} else if required[key] {
			fmt.Fprintf(&fields, "  %s: %s;\n", wireKey, kind)
		} else {
			fmt.Fprintf(&fields, "  %s?: %s;\n", wireKey, kind)
		}
	}
	g.count++
	name := fmt.Sprintf("TaskObject%d", g.count)
	if g.python {
		fmt.Fprintf(&g.objects, "%s = typing.TypedDict(\n    %q,\n    {\n%s    },\n)\n\n", name, name, fields.String())
	} else {
		fmt.Fprintf(&g.objects, "type %s = {\n%s", name, fields.String())
		if additional != false {
			fmt.Fprintln(&g.objects, "  [key: string]: unknown;")
		}
		fmt.Fprint(&g.objects, "};\n\n")
	}
	return name, nil
}

func sortedBindingKeys(values map[string]any) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}
