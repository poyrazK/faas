package daemonunitspec

import (
	"strings"
	"testing"
)

func TestInternalMailIsOptionalUnprivilegedAndDisabledByDefault(t *testing.T) {
	for _, e := range Registry {
		if e.Name == "maild" {
			t.Fatal("internal experiment entered automatic fleet activation")
		}
	}
	found := false
	for _, e := range OptionalRegistry {
		if e.Name == "maild" {
			found = true
		}
	}
	if !found {
		t.Fatal("missing optional unit")
	}
	u := UnitMaild()
	if u.User == "root" || !u.NoNewPrivileges || len(u.CapabilityBoundingSet) != 0 {
		t.Fatal("privileged mail service")
	}
	rendered := string(u.Render())
	if !strings.Contains(rendered, "FAAS_INTERNAL_MAIL_RELAY_BACKPRESSURE_ENABLED=0") {
		t.Fatal("relay backpressure must default off")
	}
	if !strings.Contains(rendered, "FAAS_INTERNAL_MAIL_DOMAIN_PACING_ENABLED=0") {
		t.Fatal("domain pacing must default off")
	}
	for _, flag := range []string{"FAAS_INTERNAL_MAIL_DEPLOYMENT_FAILED_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_SUBSCRIPTION_ENDED_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_QUOTA_WARNING_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_NONPAYMENT_DELETION_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_ACCOUNT_SUSPENDED_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_ACCOUNT_RESTORED_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_MANAGED_POSTGRES_CAP_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_PAYMENT_FAILED_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_MFA_ENABLED_ALERT_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_PASSWORD_CHANGED_ALERT_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_MFA_DISABLED_ALERT_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_MFA_DISABLE_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_MFA_RECOVERY_ALERT_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_MAGIC_LINK_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_PASSWORD_RESET_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_VERIFICATION_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_OUTBOX_RECONCILIATION_ENABLED=0", "FAAS_INTERNAL_MAIL_PRODUCER_OUTBOX_ENABLED=0", "FAAS_INTERNAL_MAIL_RECOVERY_ENABLED=0", "FAAS_INTERNAL_MAIL_SUPPRESSION_CONTROLS_ENABLED=0", "FAAS_INTERNAL_MAIL_ENCRYPTION_ROTATION_ENABLED=0", "FAAS_INTERNAL_MAIL_PRODUCER_LIFECYCLE_ENABLED=0", "FAAS_INTERNAL_MAIL_PRODUCER_SCHEDULING_ENABLED=0", "FAAS_INTERNAL_MAIL_EVENT_FEED_ENABLED=0", "FAAS_INTERNAL_MAIL_REPUTATION_ENABLED=0", "FAAS_INTERNAL_MAIL_ENABLED=0", "FAAS_INTERNAL_MAIL_DELIVERY_ENABLED=0", "FAAS_INTERNAL_MAIL_REPORTS_ENABLED=0", "FAAS_INTERNAL_MAIL_FEEDBACK_ENABLED=0", "FAAS_INTERNAL_MAIL_RETENTION_ENABLED=0", "FAAS_INTERNAL_MAIL_OPERATIONS_ENABLED=0", "FAAS_INTERNAL_MAIL_DKIM_ROTATION_ENABLED=0", "FAAS_INTERNAL_MAIL_DOMAIN_REVERIFY_ENABLED=0", "FAAS_INTERNAL_MAIL_DELIVERY_CONTROLS_ENABLED=0", "FAAS_INTERNAL_MAIL_PRODUCERS_ENABLED=0", "FAAS_INTERNAL_MAIL_SCHEDULING_ENABLED=0"} {
		if !strings.Contains(rendered, flag) {
			t.Fatal("missing default-off flag", flag)
		}
	}
	if !strings.Contains(rendered, "LoadCredential=faas_internal_mail_age_identity:") {
		t.Fatal("missing private encryption credential")
	}
}
