// Package operationbindings renders application bindings from validated,
// deployment-resolved Customer Operation contracts.
package operationbindings

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type Contract struct {
	App, SHA256 string
	Operations  []Operation
}

type Operation struct {
	Name, Revision string
	Milestones     []string
	Workflows      []Workflow
}

type Workflow struct {
	Name                   string
	Version                int
	States, TerminalStates []string
	Transitions            []Transition
	TransitionsDeclared    bool
}

type Transition struct {
	From, To           string
	RequiredMilestones []string
}

type binding struct {
	operation string
	workflow  Workflow
}

var slug = regexp.MustCompile(`^[a-z][a-z0-9-]{0,63}$`)

// Render produces deterministic standalone code. The transaction interfaces
// are structural, so generated code needs no dependency on a specific SDK.
func Render(contract Contract, language, packageName string) ([]byte, error) {
	if language != "typescript" && language != "javascript" && language != "go" && language != "python" {
		return nil, fmt.Errorf("language must be typescript, javascript, go or python")
	}
	if language == "go" && (!token.IsIdentifier(packageName) || packageName == "_") {
		return nil, fmt.Errorf("invalid Go package name")
	}
	if !slug.MatchString(contract.App) || !regexp.MustCompile(`^[0-9a-f]{64}$`).MatchString(contract.SHA256) {
		return nil, fmt.Errorf("invalid contract identity")
	}
	operations := append([]Operation(nil), contract.Operations...)
	sort.Slice(operations, func(i, j int) bool { return operations[i].Name < operations[j].Name })
	workflows := map[string]Workflow{}
	var bindings []binding
	seenBindings := map[string]bool{}
	for _, operation := range operations {
		if !slug.MatchString(operation.Name) {
			return nil, fmt.Errorf("invalid Operation name")
		}
		for _, source := range operation.Workflows {
			workflow := source
			workflow.States = append([]string(nil), source.States...)
			workflow.TerminalStates = append([]string(nil), source.TerminalStates...)
			sort.Strings(workflow.States)
			sort.Strings(workflow.TerminalStates)
			if !slug.MatchString(workflow.Name) || workflow.Version < 1 {
				return nil, fmt.Errorf("invalid workflow identity")
			}
			for _, state := range workflow.States {
				if !slug.MatchString(state) {
					return nil, fmt.Errorf("invalid workflow state")
				}
			}
			if prior, ok := workflows[workflow.Name]; ok && (prior.Version != workflow.Version || strings.Join(prior.States, ",") != strings.Join(workflow.States, ",") || strings.Join(prior.TerminalStates, ",") != strings.Join(workflow.TerminalStates, ",")) {
				return nil, fmt.Errorf("inconsistent workflow %q", workflow.Name)
			}
			workflows[workflow.Name] = workflow
			key := operation.Name + "/" + workflow.Name
			// Multiple milestone steps share one contract.
			if seenBindings[key] {
				continue
			}
			seenBindings[key] = true
			workflow.Transitions = append([]Transition(nil), source.Transitions...)
			sort.Slice(workflow.Transitions, func(i, j int) bool {
				left, right := workflow.Transitions[i], workflow.Transitions[j]
				return left.From+"/"+left.To < right.From+"/"+right.To
			})
			for i := range workflow.Transitions {
				edge := &workflow.Transitions[i]
				if !slug.MatchString(edge.From) || !slug.MatchString(edge.To) {
					return nil, fmt.Errorf("invalid workflow edge")
				}
				edge.RequiredMilestones = append([]string(nil), edge.RequiredMilestones...)
				sort.Strings(edge.RequiredMilestones)
				for _, name := range edge.RequiredMilestones {
					if !slug.MatchString(name) {
						return nil, fmt.Errorf("invalid required milestone")
					}
				}
			}
			bindings = append(bindings, binding{operation.Name, workflow})
		}
	}
	if len(workflows) == 0 {
		return nil, fmt.Errorf("selected app has no operation_workflows")
	}
	sort.Slice(bindings, func(i, j int) bool {
		return bindings[i].workflow.Name+"/"+bindings[i].operation < bindings[j].workflow.Name+"/"+bindings[j].operation
	})
	names := make([]string, 0, len(workflows))
	for name := range workflows {
		names = append(names, name)
	}
	sort.Strings(names)
	var out bytes.Buffer
	comment := "//"
	if language == "python" {
		comment = "#"
	}
	fmt.Fprintf(&out, "%s Code generated by gregale customer-operations bindings; DO NOT EDIT.\n%s Authorize first; pass the source state read under the business-row lock.\n%s Let helper errors escape the transaction callback so all queued writes roll back.\n", comment, comment, comment)
	switch language {
	case "typescript", "javascript":
		fmt.Fprintf(&out, "export const contractSHA256 = %s;\nexport const app = %s;\n", quote(contract.SHA256), quote(contract.App))
		if language == "typescript" {
			out.WriteString("export interface WorkflowTransaction {\n  milestone(name: string, payload: unknown): void;\n  workflowTransition(workflow: string, instanceID: string, from: string, to: string): void;\n  workflowState(workflow: string, instanceID: string, state: string): void;\n}\n")
		}
	case "python":
		hasStates := false
		for _, workflow := range workflows {
			hasStates = hasStates || len(workflow.States) > 0
		}
		if hasStates {
			out.WriteString("from typing import Any, Literal, Protocol\n")
		} else {
			out.WriteString("from typing import Any, Protocol\n")
		}
		out.WriteString("\nclass WorkflowTransaction(Protocol):\n    def milestone(self, name: str, payload: Any) -> None: ...\n    def workflow_transition(self, workflow: str, instance_id: str, from_state: str, to_state: str) -> None: ...\n    def workflow_state(self, workflow: str, instance_id: str, state: str) -> None: ...\n\n")
		fmt.Fprintf(&out, "CONTRACT_SHA256 = %s\nAPP = %s\n", quote(contract.SHA256), quote(contract.App))
	case "go":
		fmt.Fprintf(&out, "package %s\n", packageName)
		for _, b := range bindings {
			if len(b.workflow.Transitions) > 0 || len(b.workflow.States) > 0 && !b.workflow.TransitionsDeclared {
				out.WriteString("import \"errors\"\n")
				break
			}
		}
		fmt.Fprintf(&out, "const ContractSHA256 = %s\nconst App = %s\n", quote(contract.SHA256), quote(contract.App))
		out.WriteString("type WorkflowTransaction interface {\nMilestone(string, any) error\nWorkflowTransition(string, string, string, string) error\nWorkflowState(string, string, string) error\n}\n")
	}
	symbols := map[string]bool{}
	addSymbol := func(name string) error {
		if symbols[name] {
			return fmt.Errorf("generated identifier collision: %s; rename the conflicting declaration", name)
		}
		symbols[name] = true
		return nil
	}
	renderConstant := func(name, value string) error {
		if err := addSymbol(name); err != nil {
			return err
		}
		switch language {
		case "typescript", "javascript":
			fmt.Fprintf(&out, "export const %s = %s;\n", name, value)
		case "python":
			fmt.Fprintf(&out, "%s = %s\n", name, value)
		case "go":
			fmt.Fprintf(&out, "const %s = %s\n", name, value)
		}
		return nil
	}
	for _, operation := range operations {
		if err := renderConstant("Operation_"+identifier(operation.Name), quote(operation.Name)); err != nil {
			return nil, err
		}
		if err := renderConstant("Revision_"+identifier(operation.Name), quote(operation.Revision)); err != nil {
			return nil, err
		}
		milestones := append([]string(nil), operation.Milestones...)
		sort.Strings(milestones)
		for _, milestone := range milestones {
			if !slug.MatchString(milestone) {
				return nil, fmt.Errorf("invalid milestone")
			}
			if err := renderConstant("Milestone_"+identifier(operation.Name)+"__"+identifier(milestone), quote(milestone)); err != nil {
				return nil, err
			}
		}
	}
	for _, name := range names {
		workflow := workflows[name]
		id := identifier(name)
		typeName := "State_" + id
		if err := addSymbol(typeName); err != nil {
			return nil, err
		}
		fmt.Fprintf(&out, "\n%s Workflow %s, contract version %d; terminal states: %s.\n", comment, name, workflow.Version, strings.Join(workflow.TerminalStates, ", "))
		if err := renderConstant("Workflow_"+id, quote(name)); err != nil {
			return nil, err
		}
		if err := renderConstant("Version_"+id, strconv.Itoa(workflow.Version)); err != nil {
			return nil, err
		}
		if len(workflow.States) == 0 {
			continue
		}
		switch language {
		case "typescript":
			fmt.Fprintf(&out, "export type %s = %s;\n", typeName, joinQuoted(workflow.States, " | "))
		case "python":
			fmt.Fprintf(&out, "%s = Literal[%s]\n", typeName, joinQuoted(workflow.States, ", "))
		case "go":
			fmt.Fprintf(&out, "type %s string\n", typeName)
		}
		for _, state := range workflow.States {
			constant := "State_" + id + "__" + identifier(state)
			if err := addSymbol(constant); err != nil {
				return nil, err
			}
			switch language {
			case "typescript":
				fmt.Fprintf(&out, "export const %s: %s = %s;\n", constant, typeName, quote(state))
			case "javascript":
				fmt.Fprintf(&out, "export const %s = %s;\n", constant, quote(state))
			case "python":
				fmt.Fprintf(&out, "%s: %s = %s\n", constant, typeName, quote(state))
			case "go":
				fmt.Fprintf(&out, "const %s %s = %s\n", constant, typeName, quote(state))
			}
		}
	}
	for _, b := range bindings {
		base := identifier(b.workflow.Name) + "__" + identifier(b.operation)
		for _, edge := range b.workflow.Transitions {
			name := "transition_" + base + "__" + identifier(edge.From) + "__" + identifier(edge.To)
			if language == "go" {
				name = "Transition_" + base + "__" + identifier(edge.From) + "__" + identifier(edge.To)
			}
			if err := addSymbol(name); err != nil {
				return nil, err
			}
			renderTransition(&out, language, name, b, edge)
		}
		if len(b.workflow.States) > 0 && len(b.workflow.Transitions) == 0 && !b.workflow.TransitionsDeclared {
			name := "report_" + base
			if language == "go" {
				name = "Report_" + base
			}
			if err := addSymbol(name); err != nil {
				return nil, err
			}
			renderSnapshot(&out, language, name, b)
		}
	}
	if language == "go" {
		return format.Source(out.Bytes())
	}
	return out.Bytes(), nil
}

func renderTransition(out *bytes.Buffer, language, name string, b binding, edge Transition) {
	typeName := "State_" + identifier(b.workflow.Name)
	params := ""
	for _, milestone := range edge.RequiredMilestones {
		param := "payload_" + identifier(milestone)
		switch language {
		case "typescript":
			params += ", " + param + ": unknown"
		case "javascript":
			params += ", " + param
		case "python":
			params += ", " + param + ": Any"
		case "go":
			params += ", " + param + " any"
		}
	}
	message := quote("workflow " + b.workflow.Name + " Operation " + b.operation + " requires source state " + edge.From)
	switch language {
	case "typescript", "javascript":
		if language == "typescript" {
			fmt.Fprintf(out, "\nexport function %s(tx: WorkflowTransaction, instanceID: string, currentState: %s%s): void {\n", name, typeName, params)
		} else {
			fmt.Fprintf(out, "\nexport function %s(tx, instanceID, currentState%s) {\n", name, params)
		}
		fmt.Fprintf(out, "  if (currentState !== %s) throw new Error(%s);\n", quote(edge.From), message)
		for i, milestone := range edge.RequiredMilestones {
			fmt.Fprintf(out, "  if (arguments.length < %d || payload_%s === undefined) throw new Error(%s);\n", i+4, identifier(milestone), quote("required milestone payload missing: "+milestone))
		}
		for _, milestone := range edge.RequiredMilestones {
			fmt.Fprintf(out, "  tx.milestone(%s, payload_%s);\n", quote(milestone), identifier(milestone))
		}
		fmt.Fprintf(out, "  tx.workflowTransition(%s, instanceID, %s, %s);\n}\n", quote(b.workflow.Name), quote(edge.From), quote(edge.To))
	case "python":
		fmt.Fprintf(out, "\ndef %s(tx: WorkflowTransaction, instance_id: str, current_state: %s%s) -> None:\n    if current_state != %s:\n        raise ValueError(%s)\n", name, typeName, params, quote(edge.From), message)
		for _, milestone := range edge.RequiredMilestones {
			fmt.Fprintf(out, "    tx.milestone(%s, payload_%s)\n", quote(milestone), identifier(milestone))
		}
		fmt.Fprintf(out, "    tx.workflow_transition(%s, instance_id, %s, %s)\n", quote(b.workflow.Name), quote(edge.From), quote(edge.To))
	case "go":
		fmt.Fprintf(out, "\nfunc %s(tx WorkflowTransaction, instanceID string, currentState %s%s) error {\nif currentState != %s { return errors.New(%s) }\n", name, typeName, params, quote(edge.From), message)
		for _, milestone := range edge.RequiredMilestones {
			fmt.Fprintf(out, "if err := tx.Milestone(%s, payload_%s); err != nil { return err }\n", quote(milestone), identifier(milestone))
		}
		fmt.Fprintf(out, "return tx.WorkflowTransition(%s, instanceID, %s, %s)\n}\n", quote(b.workflow.Name), quote(edge.From), quote(edge.To))
	}
}

func renderSnapshot(out *bytes.Buffer, language, name string, b binding) {
	typeName := "State_" + identifier(b.workflow.Name)
	message := quote("undeclared state for workflow " + b.workflow.Name)
	switch language {
	case "typescript", "javascript":
		if language == "typescript" {
			fmt.Fprintf(out, "\nexport function %s(tx: WorkflowTransaction, instanceID: string, state: %s): void {\n", name, typeName)
		} else {
			fmt.Fprintf(out, "\nexport function %s(tx, instanceID, state) {\n", name)
		}
		fmt.Fprintf(out, "  if (![%s].includes(state)) throw new Error(%s);\n  tx.workflowState(%s, instanceID, state);\n}\n", joinQuoted(b.workflow.States, ", "), message, quote(b.workflow.Name))
	case "python":
		fmt.Fprintf(out, "\ndef %s(tx: WorkflowTransaction, instance_id: str, state: %s) -> None:\n    if state not in [%s]:\n        raise ValueError(%s)\n    tx.workflow_state(%s, instance_id, state)\n", name, typeName, joinQuoted(b.workflow.States, ", "), message, quote(b.workflow.Name))
	case "go":
		fmt.Fprintf(out, "\nfunc %s(tx WorkflowTransaction, instanceID string, state %s) error {\nswitch state {\ncase %s:\nreturn tx.WorkflowState(%s, instanceID, string(state))\ndefault: return errors.New(%s)\n}\n}\n", name, typeName, joinQuoted(b.workflow.States, ", "), quote(b.workflow.Name), message)
	}
}

func identifier(value string) string { return strings.ReplaceAll(value, "-", "_") }
func quote(value string) string      { return strconv.Quote(value) }
func joinQuoted(values []string, separator string) string {
	quoted := make([]string, len(values))
	for i, value := range values {
		quoted[i] = quote(value)
	}
	return strings.Join(quoted, separator)
}
