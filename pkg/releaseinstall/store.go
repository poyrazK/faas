// UpsertComputeNode implements Store.
//
// Writes the per-node release membership on compute_nodes. The
// conflict target is compute_nodes_name_key (UNIQUE on name) per
// migrations/00024_compute_nodes.sql. The migration 00271 columns
// (release_id, manifest_hash) are plain text with no DB CHECK, so
// Go-side validation (validGitSHA + validManifestHash) is the gate.
//
// generation is intentionally set to 0 on every write — the doctor
// (PR-4) bumps it on detected drift; PR-6 does not pre-empt that
// signal. host_certificate, cert_fingerprint, and role are NOT
// touched (PR-X / PR-2 own those columns).
func (s pgStore) UpsertComputeNode(ctx context.Context, name, gitSHA, manifestHash string) (string, error) {
	if name == "" {
		return "", fmt.Errorf("releaseinstall: empty compute_nodes name")
	}
	if !validGitSHA(gitSHA) {
		return "", fmt.Errorf("releaseinstall: git_sha %q is not 40-char lowercase hex", gitSHA)
	}
	if !validManifestHash(manifestHash) {
		return "", fmt.Errorf("releaseinstall: manifest_hash %q is not sha256:<64hex>", manifestHash)
	}
	// Update first. PostgreSQL validates NOT NULL columns on the INSERT
	// arm before it considers ON CONFLICT, so the old one-statement
	// UPSERT failed against the production schema: target_url and the
	// capacity columns predate the release metadata and have no defaults.
	// Updating first also preserves the existing node's live placement
	// contract, capacity, active bit, and role.
	var id string
	err := s.pool.QueryRow(ctx, `
		update compute_nodes
		   set release_id = $2,
		       manifest_hash = $3
		 where name = $1
		returning id
	`, name, gitSHA, manifestHash).Scan(&id)
	if err == nil {
		return id, nil
	}
	if !errors.Is(err, pgx.ErrNoRows) {
		return "", fmt.Errorf("releaseinstall: update compute_nodes: %w", err)
	}

	// A genuinely new row needs the legacy single-box defaults required by
	// migrations/00024. Manifest rendering or node registration can refine
	// these fields later; release installation must not invent a NULL row.
	err = s.pool.QueryRow(ctx, `
		insert into compute_nodes
		    (name, target_url, vpcpus, mem_mb, max_concurrency,
		     admission_ceiling_mb, release_id, manifest_hash, generation)
		values ($1, 'unix:///run/faas/vmmd.sock', 160, 56000, 200,
		        47600, $2, $3, 0)
		on conflict (name) do nothing
		returning id
	`, name, gitSHA, manifestHash).Scan(&id)
	if err == nil {
		return id, nil
	}
	if !errors.Is(err, pgx.ErrNoRows) {
		return "", fmt.Errorf("releaseinstall: insert compute_nodes: %w", err)
	}
	// Another installer won the race between the update and insert. Read
	// its row and leave its placement fields untouched.
	if err := s.pool.QueryRow(ctx, `select id from compute_nodes where name = $1`, name).Scan(&id); err != nil {
		return "", fmt.Errorf("releaseinstall: reread compute_nodes: %w", err)
	}
	return id, nil
}

// GetComputeNode implements Store.
func (s pgStore) GetComputeNode(ctx context.Context, name string) (ComputeNodeRow, error) {
	if name == "" {
		return ComputeNodeRow{}, fmt.Errorf("releaseinstall: empty compute_nodes name")
	}
	var (
		row                     ComputeNodeRow
		releaseID, manifestHash *string
	)
	err := s.pool.QueryRow(ctx, `
		select id, name, release_id, manifest_hash,
		       host_certificate, cert_fingerprint, role, generation,
		       lifecycle::text, active
		  from compute_nodes
		 where name = $1
	`, name).Scan(
		&row.ID, &row.Name, &releaseID, &manifestHash,
		&row.HostCertificate, &row.CertFingerprint, &row.Role, &row.Generation,
	)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return ComputeNodeRow{}, ErrComputeNodeNotFound
		}
		return ComputeNodeRow{}, fmt.Errorf("releaseinstall: get compute node: %w", err)
	}
	if releaseID != nil {
		row.ReleaseID = *releaseID
	}
	if manifestHash != nil {
		row.ManifestHash = *manifestHash
	}
	return row, nil
}

// ListComputeNodes implements Store. Returns every row in
// compute_nodes ordered by name (PQ-stable). PR-4 doctor walks
// the result to detect per-node drift against the on-disk
// bundle + the release_bundles table. The widening to eight
// columns mirrors GetComputeNode — nullable pointers stay nil
// on NULL.
func (s pgStore) ListComputeNodes(ctx context.Context) ([]ComputeNodeRow, error) {
	rows, err := s.pool.Query(ctx, `
		select id, name, release_id, manifest_hash,
		       host_certificate, cert_fingerprint, role, generation
		  from compute_nodes
		 order by name
	`)
	if err != nil {
		return nil, fmt.Errorf("releaseinstall: list compute nodes: %w", err)
	}
	defer rows.Close()
	var out []ComputeNodeRow
	for rows.Next() {
		var (
			row                     ComputeNodeRow
			releaseID, manifestHash *string
		)
		if err := rows.Scan(
			&row.ID, &row.Name, &releaseID, &manifestHash,
			&row.HostCertificate, &row.CertFingerprint, &row.Role, &row.Generation,
			&row.Lifecycle, &row.Active,
		); err != nil {
			return nil, fmt.Errorf("releaseinstall: scan compute_nodes: %w", err)
		}
		if releaseID != nil {
			row.ReleaseID = *releaseID
		}
		if manifestHash != nil {
			row.ManifestHash = *manifestHash
		}
		out = append(out, row)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("releaseinstall: iterate compute_nodes: %w", err)
	}
	return out, nil
}

// SetComputeNodeRole implements Store (PR-2 / issue #911 / ADR-110).
// Writes the role column on the row keyed by name. The query is
// intentional: a plain UPDATE returns ErrNotFound via pgx.ErrNoRows
// only when the row doesn't exist (Postgres skips the WHERE silently
// when zero rows match, so we use RETURNING + a follow-up scan to
// distinguish "no row" from "row already had the same role").
//
// The role column is plain text per migrations/00271; the
// single-box / control-plane / compute-only enum is enforced by the
// renderer (the only writer), not the DB. PR-4 doctor reads the
// column to verify the renderer's claim matches the on-disk
// daemonset.
func (s pgStore) SetComputeNodeRole(ctx context.Context, name, role string) (bool, error) {
	if name == "" {
		return false, fmt.Errorf("releaseinstall: empty compute_nodes name")
	}
	if !canonicalComputeNodeRoles[role] {
		return false, fmt.Errorf("%w (got %q)", ErrInvalidRole, role)
	}
	// Conditional UPDATE returns the row only when the role actually
	// changed; if the row already has the role, RETURNING is empty
	// and we treat it as a no-op (false). The follow-up lookup
	// distinguishes "no row" (ErrComputeNodeNotFound) from "row +
	// same role" (false, nil).
	var newRole string
	err := s.pool.QueryRow(ctx, `
		update compute_nodes
		   set role = $2
		 where name = $1
		   and (role IS DISTINCT FROM $2)
		returning role
	`, name, role).Scan(&newRole)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			// Either the row doesn't exist, or it already has
			// the role. Disambiguate.
			row, gerr := s.GetComputeNode(ctx, name)
			if gerr != nil {
				return false, gerr
			}
			// Row exists; same role.
			_ = row
			return false, nil
		}
		return false, fmt.Errorf("releaseinstall: set compute_nodes role: %w", err)
	}
	return true, nil
}

// StampHostCertificate implements Store. Conditional UPDATE keyed
// by name; returns ErrComputeNodeNotFound when the row is absent
// (the doctor's row-walk never lands here because PR-6 stamps the
// row first, but the safety net matters for the
// `gregalectl secrets init` first-run path where the operator
// hasn't yet run releaseinstall).
func (s pgStore) StampHostCertificate(ctx context.Context, name, pem, fingerprint string) error {
	if name == "" {
		return fmt.Errorf("releaseinstall: empty compute_nodes name")
	}
	if pem == "" {
		return fmt.Errorf("releaseinstall: empty host_certificate pem")
	}
	if fingerprint == "" {
		return fmt.Errorf("releaseinstall: empty cert_fingerprint")
	}
	tag, err := s.pool.Exec(ctx, `
		update compute_nodes
		   set host_certificate = $2,
		       cert_fingerprint = $3
		 where name = $1
	`, name, pem, fingerprint)
	if err != nil {
		return fmt.Errorf("releaseinstall: stamp host cert: %w", err)
	}
	if tag.RowsAffected() == 0 {
		return ErrComputeNodeNotFound
	}
	return nil
}

// BumpComputeNodeGeneration implements Store. Atomic
// generation = generation + 1 RETURNING — the next doctor run
// picks up the delta as a generation-bump finding rather than a
// stale-fingerprint finding (the audit trail the operator needs).
func (s pgStore) BumpComputeNodeGeneration(ctx context.Context, name string) (int, error) {
	if name == "" {
		return 0, fmt.Errorf("releaseinstall: empty compute_nodes name")
	}
	var newGen int
	err := s.pool.QueryRow(ctx, `
		update compute_nodes
		   set generation = coalesce(generation, 0) + 1
		 where name = $1
		returning generation
	`, name).Scan(&newGen)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return 0, ErrComputeNodeNotFound
		}
		return 0, fmt.Errorf("releaseinstall: bump generation: %w", err)
	}
	return newGen, nil
}
