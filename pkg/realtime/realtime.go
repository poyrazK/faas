// Package realtime owns Gregale's managed realtime data plane.
//
// Managed realtime is deliberately separate from the gateway's raw Upgrade
// bridge. The raw bridge forwards bytes to an application-owned socket; this
// package terminates WebSocket connections at Gregale, keeps the connection
// registry in the process that owns the sockets, and exposes message delivery
// as ordinary callback events.
