package clientgen

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"
	"unicode"

	"github.com/onebox-faas/faas/pkg/dataapi"
)

// names hands out unique identifiers; collisions get a numeric suffix.
type names struct{ used map[string]bool }

func newNames(reserved ...string) *names {
	n := &names{used: map[string]bool{}}
	for _, r := range reserved {
		n.used[r] = true
	}
	return n
}

func (n *names) take(base string) string {
	name := base
	for i := 2; n.used[name]; i++ {
		name = fmt.Sprintf("%s%d", base, i)
	}
	n.used[name] = true
	return name
}

func words(value string) []string {
	return strings.FieldsFunc(value, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
}

// pascal maps a database name to an exported identifier, e.g. note_tags -> NoteTags.
func pascal(value string) string {
	var b strings.Builder
	for _, word := range words(value) {
		runes := []rune(word)
		b.WriteString(strings.ToUpper(string(runes[0])) + string(runes[1:]))
	}
	out := b.String()
	if out == "" || unicode.IsDigit([]rune(out)[0]) {
		out = "X" + out
	}
	return out
}

// snake maps a database name to a lower-case identifier.
func snake(value string) string {
	out := strings.ToLower(strings.Join(words(value), "_"))
	if out == "" || unicode.IsDigit([]rune(out)[0]) {
		out = "x_" + out
	}
	return out
}

type enumDef struct {
	Key    string // schema.name in the snapshot
	Name   string
	Labels []string
}

type tableDef struct {
	dataapi.Table
	Base string // identifier stem for Row/Insert/Update types
}

type functionDef struct {
	dataapi.Function
	Base    string
	Returns Type
}

// model resolves identifiers once so both renderers agree on names.
type model struct {
	Fingerprint string
	Schemas     []string
	Enums       []enumDef
	enumByKey   map[string]string // canonical labels JSON -> type name
	Composites  []dataapi.Composite
	compositeNm map[string]string
	Tables      []tableDef
	tableByKey  map[string]tableDef
	Functions   []functionDef
}

func qualified(schemas []string, schema, name string) string {
	if len(schemas) > 1 {
		return schema + "_" + name
	}
	return name
}

func buildModel(contract dataapi.Contract) model {
	s := contract.Parsed
	m := model{Fingerprint: contract.Fingerprint, Schemas: s.Schemas, enumByKey: map[string]string{}, compositeNm: map[string]string{}, tableByKey: map[string]tableDef{}}
	types := newNames("Client", "Error", "Table", "Json")
	keys := make([]string, 0, len(s.Enums))
	for key := range s.Enums {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		schema, name, _ := strings.Cut(key, ".")
		labels, _ := json.Marshal(s.Enums[key])
		if _, exists := m.enumByKey[string(labels)]; exists || len(s.Enums[key]) == 0 {
			continue
		}
		def := enumDef{Key: key, Name: types.take(pascal(qualified(s.Schemas, schema, name))), Labels: s.Enums[key]}
		m.enumByKey[string(labels)] = def.Name
		m.Enums = append(m.Enums, def)
	}
	for _, c := range s.Composites {
		m.compositeNm[c.Schema+"."+c.Name] = types.take(pascal(qualified(s.Schemas, c.Schema, c.Name)) + "Composite")
		m.Composites = append(m.Composites, c)
	}
	for _, t := range s.Tables {
		base := pascal(qualified(s.Schemas, t.Schema, t.Name))
		for _, suffix := range []string{"Row", "Insert", "Update"} {
			if types.used[base+suffix] {
				base = types.take(base)
				break
			}
		}
		for _, suffix := range []string{"Row", "Insert", "Update"} {
			types.used[base+suffix] = true
		}
		def := tableDef{Table: t, Base: base}
		m.Tables = append(m.Tables, def)
		m.tableByKey[t.Schema+"."+t.Name] = def
	}
	for _, f := range s.Functions {
		m.Functions = append(m.Functions, functionDef{Function: f, Base: types.take(pascal(qualified(s.Schemas, f.Schema, f.Name)) + "Args"), Returns: ParseType(f.Returns)})
	}
	return m
}

func (m model) enumName(t Type) string {
	labels, _ := json.Marshal(t.Literals)
	return m.enumByKey[string(labels)]
}

func header(comment, fingerprint string) string {
	return comment + " Code generated by gregale data-api types. DO NOT EDIT.\n" + comment + " Schema fingerprint: " + fingerprint + "\n"
}
