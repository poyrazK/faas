const (
	runStepTimeout  = 8 * time.Second
	maxRunStepBody  = 256 << 10
	maxAssertions   = 5
	maxAssertionLen = 512
)

func validateAssertions(method string, assertions []api.APISandboxJSONAssertion) error {
	if len(assertions) > maxAssertions || (len(assertions) > 0 && method == http.MethodHead) {
		return fmt.Errorf("use up to %d JSON assertions on requests with a response body", maxAssertions)
	}
	for i := range assertions {
		assertion := &assertions[i]
		_, ok := assertionPointer(assertion.Pointer)
		raw := bytes.TrimSpace(assertion.Equals)
		if !ok || len(raw) == 0 || len(raw) > maxAssertionLen || raw[0] == '{' || raw[0] == '[' || !json.Valid(raw) {
			return fmt.Errorf("assertion %d requires a JSON Pointer and a scalar equals value", i+1)
		}
		assertion.Equals = raw
	}
	return nil
}

func assertionPointer(pointer string) ([]string, bool) {
	if pointer == "" {
		return nil, true
	}
	if len(pointer) > maxAssertionLen || pointer[0] != '/' ||
		strings.ContainsFunc(pointer, func(r rune) bool { return r < 0x20 || r == 0x7f }) {
		return nil, false
	}
	parts := strings.Split(pointer[1:], "/")
	for n, value := range parts {
		for i := 0; i < len(value); i++ {
			if value[i] == '~' {
				i++
				if i == len(value) || (value[i] != '0' && value[i] != '1') {
					return nil, false
				}
			}
		}
		parts[n] = strings.ReplaceAll(strings.ReplaceAll(value, "~1", "/"), "~0", "~")
	}
	return parts, true
}

func assertionValue(root any, parts []string) (any, bool) {
	current := root
	for _, part := range parts {
		switch value := current.(type) {
		case map[string]any:
			var found bool
			current, found = value[part]
			if !found {
				return nil, false
			}
		case []any:
			index, err := strconv.Atoi(part)
			if err != nil || index < 0 || index >= len(value) || strconv.Itoa(index) != part {
				return nil, false
			}
			current = value[index]
		default:
			return nil, false
		}
	}
	return current, true
}

// RunStep sends one saved request to a verified sandbox. Only report metadata
// leaves this function. Callers checkpoint its result before the next step.
func RunStep(ctx context.Context, client *http.Client, base, deploymentID, token string, index int, step api.APISandboxExampleRequest) api.APISandboxRunStep {
	start := time.Now()
	result := api.APISandboxRunStep{Index: index, Method: step.Method, Title: step.Title, ExpectedStatus: step.ExpectedStatus}
	result.FailureCode = runStep(ctx, client, base, deploymentID, token, step, &result)
	result.DurationMS = time.Since(start).Milliseconds()
	return result
}

func runStep(ctx context.Context, client *http.Client, base, deploymentID, token string, step api.APISandboxExampleRequest, result *api.APISandboxRunStep) string {
	if !validExampleTarget(step.Path) {
		return "invalid_request"
	}
	if client == nil {
		client = http.DefaultClient
	}
	prober := *client
	prober.Timeout = runStepTimeout
	prober.Jar = nil
	prober.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	var body io.Reader
	if len(step.Body) != 0 {
		body = bytes.NewReader(step.Body)
	}
	req, err := http.NewRequestWithContext(ctx, step.Method, base+step.Path, body)
	if err != nil {
		return "invalid_request"
	}
	requestID := uuid.NewString()
	req.Header.Set(api.RequestIDHeader, requestID)
	req.Header.Set("Authorization", "Bearer "+token)
	req.Header.Set("Cache-Control", "no-cache")
	req.Header.Set("Accept", "application/json")
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := prober.Do(req)
	if err != nil {
		return "request_unavailable"
	}
	defer func() { _ = resp.Body.Close() }()
	result.HTTPStatus = resp.StatusCode
	// The public gateway owns this header. Keep only the correlation ID we
	// supplied, or a canonical UUID generated by an upstream gateway.
	if id, err := uuid.Parse(resp.Header.Get(api.RequestIDHeader)); err == nil && id != uuid.Nil && id.String() == resp.Header.Get(api.RequestIDHeader) {
		result.RequestID = id.String()
	}
	if deploymentID == "" || !slices.Equal(resp.Header.Values(api.RevisionHeader), []string{deploymentID}) {
		return "deployment_mismatch"
	}
	if resp.StatusCode != step.ExpectedStatus {
		return "unexpected_http_status"
	}
	if len(step.Assertions) == 0 {
		return ""
	}
	raw, err := io.ReadAll(io.LimitReader(resp.Body, maxRunStepBody+1))
	if err != nil || len(raw) > maxRunStepBody {
		return "invalid_json_response"
	}
	return CheckJSONAssertions(raw, step.Assertions, result)
}

// CheckJSONAssertions records a failing pointer without retaining either value.
func CheckJSONAssertions(raw []byte, assertions []api.APISandboxJSONAssertion, result *api.APISandboxRunStep) string {
	if !json.Valid(raw) {
		return "invalid_json_response"
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.UseNumber()
	var response any
	if err := decoder.Decode(&response); err != nil {
		return "invalid_json_response"
	}
	for i, assertion := range assertions {
		parts, valid := assertionPointer(assertion.Pointer)
		value, found := assertionValue(response, parts)
		if !valid || !found || !assertionMatches(value, assertion.Equals) {
			result.FailedAssertion = i + 1
			result.FailedPointer = assertion.Pointer
			return "json_assertion_failed"
		}
	}
	return ""
}

func assertionMatches(value any, expected json.RawMessage) bool {
	switch v := value.(type) {
	case nil, string, bool:
	case json.Number:
		if len(v) > maxAssertionLen {
			return false
		}
	default:
		return false
	}
	raw, err := json.Marshal(value)
	return err == nil && storedworkflowchecks.EqualJSON(raw, expected)
}

// WaitForState polls a read-only assertion after asynchronous delivery. It
// keeps the last check's evidence and never repeats the webhook.
func WaitForState(ctx context.Context, client *http.Client, base, deploymentID, token string, index int, check api.APISandboxExampleRequest, timeout time.Duration) api.APISandboxRunStep {
	start := time.Now()
	path, _, _ := strings.Cut(check.Path, "?")
	result := api.APISandboxRunStep{
		Index: index, Title: check.Title, Method: check.Method, Path: path, ExpectedStatus: check.ExpectedStatus,
	}
	if check.Method != http.MethodGet || len(check.Assertions) == 0 {
		result.FailureCode = "invalid_request"
		return result
	}
	waitCtx, stop := context.WithTimeout(ctx, timeout)
	defer stop()
	ticker := time.NewTicker(500 * time.Millisecond)
	defer ticker.Stop()
	for {
		attempt := RunStep(waitCtx, client, base, deploymentID, token, index, check)
		if waitCtx.Err() != nil {
			break
		}
		result = attempt
		result.Path, result.DurationMS = path, time.Since(start).Milliseconds()
		switch result.FailureCode {
		case "json_assertion_failed", "request_unavailable":
		case "unexpected_http_status":
			if result.HTTPStatus != http.StatusNotFound && result.HTTPStatus != http.StatusTooManyRequests &&
				result.HTTPStatus < http.StatusInternalServerError {
				return result
			}
		default:
			return result
		}
		select {
		case <-waitCtx.Done():
			result.FailureCode, result.DurationMS = "webhook_state_timeout", time.Since(start).Milliseconds()
			return result
		case <-ticker.C:
		}
	}
	result.FailureCode, result.DurationMS = "webhook_state_timeout", time.Since(start).Milliseconds()
	return result
}
