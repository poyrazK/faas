// featureRouteActions reviews the app endpoints routeActions did not list,
// grouped by feature (bug hunt 37). Before it, an unlisted endpoint fell back
// to the creator alone, and only while an owner or admin, so on a company app
// no other member could use it and nobody could once the creator left.
//
// The rules follow routeActions':
//   - reads take OrgActionReadApp; reads of request data, payloads, stack
//     traces, profiles and other evidence take OrgActionReadAppLogs;
//   - configuration writes take OrgActionConfigureApp; runs, replays, deploys
//     and other actions on live work take OrgActionDeployApp;
//   - features that hold or reveal credentials, money or end-user data
//     (consumers, product billing and customers, realtime, inbound webhooks,
//     outbound bindings, tokens, registry credentials, crash snapshots), live
//     connections into the app's data, and writes that change exposure,
//     policies, gates or repository bindings take OrgActionManageAppSecurity,
//     owners and admins only, whoever created the app.
//
