// GoFunctionTypesFile is written into a Go function's root. It declares a
// struct per callee schema and a `functions` value with a typed method per
// callee over the SDK's generic client (ADR-20261112160000 §4).
const GoFunctionTypesFile = "gregale_functions.go"

// goFunctionsImport is the Go SDK's generic function client.
const goFunctionsImport = "github.com/gregale-dev/gregale-go/functions"

var goKeywords = map[string]bool{
	"break": true, "case": true, "chan": true, "const": true, "continue": true, "default": true, "defer": true,
	"else": true, "fallthrough": true, "for": true, "func": true, "go": true, "goto": true, "if": true,
	"import": true, "interface": true, "map": true, "package": true, "range": true, "return": true,
	"select": true, "struct": true, "switch": true, "type": true, "var": true,
}

type goTypes struct {
	defs  []string
	names map[string]bool
}

func (g *goTypes) uniqueName(base string) string {
	name := base
	for i := 2; g.names[name]; i++ {
		name = fmt.Sprintf("%s%d", base, i)
	}
	g.names[name] = true
	return name
}

// goInitialisms are spelled in capitals, as Go names spell them.
var goInitialisms = map[string]bool{
	"api": true, "cpu": true, "css": true, "dns": true, "html": true, "http": true, "https": true, "id": true,
	"ip": true, "json": true, "sql": true, "ttl": true, "uid": true, "uri": true, "url": true, "uuid": true, "xml": true,
}

// goExported is name as an exported Go identifier: "user_id" -> "UserID".
func goExported(name string) string {
	var b strings.Builder
	words := strings.FieldsFunc(name, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
	for _, w := range words {
		if goInitialisms[strings.ToLower(w)] {
			b.WriteString(strings.ToUpper(w))
			continue
		}
		r := []rune(w)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	s := b.String()
	if s == "" || unicode.IsDigit(rune(s[0])) {
		s = "X" + s
	}
	return s
}

func goFunctionTypes(pkg string, callees []typedCallee) (string, error) {
	if pkg == "" || !pyIdent.MatchString(pkg) || goKeywords[pkg] {
		pkg = "main"
	}
	g := &goTypes{names: map[string]bool{"gregaleFunctions": true}}
	type method struct{ name, call, in, out string }
	methods := make([]method, 0, len(callees))
	used := map[string]bool{}
	for _, c := range callees {
		stem := goExported(c.name)
		for used[stem] || used["Send"+stem] {
			stem += "_"
		}
		used[stem], used["Send"+stem] = true, true
		in := g.goType(c.input, stem+"Input", true)
		out := g.goType(c.output, stem+"Output", true)
		methods = append(methods, method{stem, c.name, in, out})
	}
	var b strings.Builder
	b.WriteString("// Code generated by `gregale function types`; DO NOT EDIT.\n")
	b.WriteString("// " + functionTypesHeader + "\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	if len(methods) > 0 {
		fmt.Fprintf(&b, "import (\n\t\"context\"\n\n\tgregalefunctions %q\n)\n\n", goFunctionsImport)
	}
	for _, def := range g.defs {
		b.WriteString(def + "\n")
	}
	b.WriteString("// gregaleFunctions has a typed method per function this function may call.\n")
	b.WriteString("type gregaleFunctions struct{}\n\n")
	b.WriteString("// functions calls the functions this function may call.\n")
	b.WriteString("var functions gregaleFunctions\n")
	for _, m := range methods {
		fmt.Fprintf(&b, "\n// %s calls the %s function and decodes its answer.\n", m.name, m.call)
		fmt.Fprintf(&b, "func (gregaleFunctions) %s(ctx context.Context, in %s, opts ...gregalefunctions.Option) (%s, error) {\n", m.name, m.in, m.out)
		fmt.Fprintf(&b, "\treturn gregalefunctions.Call[%s, %s](ctx, %q, in, opts...)\n}\n", m.in, m.out, m.call)
		fmt.Fprintf(&b, "\n// Send%s enqueues a durable async invocation of the %s function.\n", m.name, m.call)
		fmt.Fprintf(&b, "func (gregaleFunctions) Send%s(ctx context.Context, in %s, opts ...gregalefunctions.Option) (*gregalefunctions.Invocation, error) {\n", m.name, m.in)
		fmt.Fprintf(&b, "\treturn gregalefunctions.Send(ctx, %q, in, opts...)\n}\n", m.call)
		fmt.Fprintf(&b, "\n// Start%s starts a run of the %s workflow function.\n", m.name, m.call)
		fmt.Fprintf(&b, "func (gregaleFunctions) Start%s(ctx context.Context, in %s, opts ...gregalefunctions.Option) (*gregalefunctions.Run, error) {\n", m.name, m.in)
		fmt.Fprintf(&b, "\treturn gregalefunctions.Start(ctx, %q, in, opts...)\n}\n", m.call)
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("format generated Go: %w", err)
	}
	return string(src), nil
}

// goType returns the Go type for schema v. Objects with properties become
// named structs; top marks a function's own input or output, whose struct
// takes the stem name.
func (g *goTypes) goType(v any, name string, top bool) string {
	m, ok := schemaMap(v)
	if !ok {
		return "any"
	}
	if c, ok := m["const"]; ok {
		return goLiteralType(c)
	}
	if list, ok := m["enum"].([]any); ok && len(list) > 0 {
		t := goLiteralType(list[0])
		for _, e := range list[1:] {
			if goLiteralType(e) != t {
				return "any"
			}
		}
		return t
	}
	if _, ok := m["anyOf"]; ok {
		return "any"
	}
	if _, ok := m["oneOf"]; ok {
		return "any"
	}
	types := schemaTypes(m)
	nullable := false
	var nonNull []string
	for _, t := range types {
		if t == "null" {
			nullable = true
		} else {
			nonNull = append(nonNull, t)
		}
	}
	if len(nonNull) != 1 {
		return "any"
	}
	t := g.goSingleType(nonNull[0], m, name, top)
	if nullable {
		return goPointer(t)
	}
	return t
}

func goLiteralType(v any) string {
	switch v.(type) {
	case string:
		return "string"
	case bool:
		return "bool"
	case float64:
		return "float64"
	}
	return "any"
}

// goPointer makes t nullable; slices, maps and any already are.
func goPointer(t string) string {
	if t == "any" || strings.HasPrefix(t, "[]") || strings.HasPrefix(t, "map[") || strings.HasPrefix(t, "*") {
		return t
	}
	return "*" + t
}

func (g *goTypes) goSingleType(t string, m map[string]any, name string, top bool) string {
	switch t {
	case "string":
		return "string"
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		return "[]" + g.goType(m["items"], name+"Item", false)
	case "object":
		names, props := sortedProperties(m)
		extra, extraIsSchema := schemaMap(m["additionalProperties"])
		if len(names) == 0 {
			if extraIsSchema {
				return "map[string]" + g.goType(extra, name+"Value", false)
			}
			return "map[string]any"
		}
		structName := name
		if !top || g.names[name] {
			structName = g.uniqueName(name)
		} else {
			g.names[name] = true
		}
		required := requiredSet(m)
		fieldNames := map[string]bool{}
		fields := make([]string, 0, len(names))
		for _, prop := range names {
			field := goExported(prop)
			for fieldNames[field] {
				field += "_"
			}
			fieldNames[field] = true
			typ := g.goType(props[prop], structName+goExported(prop), false)
			tag := prop
			if !required[prop] {
				typ = goPointer(typ)
				tag += ",omitempty"
			}
			fields = append(fields, fmt.Sprintf("\t%s %s `json:%q`", field, typ, tag))
		}
		g.defs = append(g.defs, fmt.Sprintf("type %s struct {\n%s\n}\n", structName, strings.Join(fields, "\n")))
		return structName
	}
	return "any"
}
