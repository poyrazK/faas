// Generated typed clients for function-to-function calls
// (ADR-20261111150000 §1). Each Node or Python function in a functions project
// gets one file in its root describing the functions it may call: its
// siblings with the input and output types their schemas declare, and its
// `calls:` apps with unknown types. The file only adds types; the runtime
// client in the SDK does the calling.

const (
	// NodeFunctionTypesFile is written into a Node function's root. It
	// augments GregaleFunctions in @gregale/sdk-node/functions/runtime.
	NodeFunctionTypesFile = "gregale-functions.d.ts"
	// PythonFunctionTypesFile is written into a Python function's root. It
	// exports a `functions` object typed by each callee's schemas.
	PythonFunctionTypesFile = "gregale_functions.py"

	functionTypesHeader = "Generated by `gregale function types` from each function's input and output schema. Do not edit; run it again after a schema changes."
)

// TypedFunction is one function of a project as the type generator sees it.
type TypedFunction struct {
	Name    string
	Root    string // slash-separated, relative to the project
	Runtime string
	Input   json.RawMessage
	Output  json.RawMessage
	Calls   FunctionCalls
}

// FunctionTypesFile is one generated file.
type FunctionTypesFile struct {
	// Function names the function whose root holds the file.
	Function string
	// Path is slash-separated, relative to the project.
	Path    string
	Content string
}

// GenerateFunctionTypes returns the typed-client file for every Node and
// Python function in fns, sorted by path. Functions in other runtimes get
// none; they call siblings through their SDK transport directly.
func GenerateFunctionTypes(fns []TypedFunction) ([]FunctionTypesFile, error) {
	byName := make(map[string]TypedFunction, len(fns))
	for _, fn := range fns {
		byName[fn.Name] = fn
	}
	var out []FunctionTypesFile
	for _, fn := range fns {
		callees := make([]typedCallee, 0, len(fn.Calls.Names))
		for _, name := range slices.Sorted(mapKeys(fn.Calls.Names)) {
			callee := typedCallee{name: name}
			if sibling, ok := byName[name]; ok {
				var err error
				if callee.input, err = decodeSchema(sibling.Name, "input", sibling.Input); err != nil {
					return nil, err
				}
				if callee.output, err = decodeSchema(sibling.Name, "output", sibling.Output); err != nil {
					return nil, err
				}
			}
			callees = append(callees, callee)
		}
		switch {
		case strings.HasPrefix(fn.Runtime, "node"):
			out = append(out, FunctionTypesFile{Function: fn.Name, Path: path.Join(fn.Root, NodeFunctionTypesFile), Content: nodeFunctionTypes(callees)})
		case strings.HasPrefix(fn.Runtime, "python"):
			out = append(out, FunctionTypesFile{Function: fn.Name, Path: path.Join(fn.Root, PythonFunctionTypesFile), Content: pythonFunctionTypes(callees)})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out, nil
}

type typedCallee struct {
	name          string
	input, output any // decoded JSON Schema; nil when none is declared
}

func decodeSchema(fn, field string, raw json.RawMessage) (any, error) {
	if len(raw) == 0 {
		return nil, nil
	}
	var v any
	if err := json.Unmarshal(raw, &v); err != nil {
		return nil, fmt.Errorf("function %q: %s schema: %w", fn, field, err)
	}
	return v, nil
}

func mapKeys(m map[string]string) func(func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

// typeName is the PascalCase stem for a function's generated types:
// "billing-api" -> "BillingApi".
func typeName(name string) string {
	var b strings.Builder
	upper := true
	for _, r := range name {
		if r == '-' || r == '_' || r == '.' {
			upper = true
			continue
		}
		if upper && r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		upper = false
		b.WriteRune(r)
	}
	s := b.String()
	if s == "" || s[0] >= '0' && s[0] <= '9' {
		s = "Fn" + s
	}
	return s
}

func schemaMap(v any) (map[string]any, bool) {
	m, ok := v.(map[string]any)
	return m, ok
}

func schemaTypes(m map[string]any) []string {
	switch t := m["type"].(type) {
	case string:
		return []string{t}
	case []any:
		var out []string
		for _, v := range t {
			if s, ok := v.(string); ok {
				out = append(out, s)
			}
		}
		return out
	}
	if _, ok := m["properties"]; ok {
		return []string{"object"}
	}
	return nil
}

func requiredSet(m map[string]any) map[string]bool {
	out := map[string]bool{}
	if list, ok := m["required"].([]any); ok {
		for _, v := range list {
			if s, ok := v.(string); ok {
				out[s] = true
			}
		}
	}
	return out
}

func sortedProperties(m map[string]any) ([]string, map[string]any) {
	props, _ := schemaMap(m["properties"])
	names := make([]string, 0, len(props))
	for k := range props {
		names = append(names, k)
	}
	sort.Strings(names)
	return names, props
}

func jsonLiteral(v any) string {
	b, _ := json.Marshal(v)
	return string(b)
}

// ---- TypeScript ----

var tsIdent = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func tsKey(name string) string {
	if tsIdent.MatchString(name) {
		return name
	}
	return jsonLiteral(name)
}

func nodeFunctionTypes(callees []typedCallee) string {
	var b strings.Builder
	b.WriteString("// " + functionTypesHeader + "\n")
	b.WriteString("import '@gregale/sdk-node/functions/runtime';\n\n")
	for _, c := range callees {
		stem := typeName(c.name)
		fmt.Fprintf(&b, "export type %sInput = %s;\n", stem, tsType(c.input, ""))
		fmt.Fprintf(&b, "export type %sOutput = %s;\n\n", stem, tsType(c.output, ""))
	}
	b.WriteString("declare module '@gregale/sdk-node/functions/runtime' {\n")
	b.WriteString("  interface GregaleFunctions {\n")
	for _, c := range callees {
		stem := typeName(c.name)
		fmt.Fprintf(&b, "    %s: { input: %sInput; output: %sOutput };\n", tsKey(c.name), stem, stem)
	}
	b.WriteString("  }\n}\n")
	return b.String()
}

// tsType renders the JSON Schema subset the adapters check; anything else is
// unknown, so a richer schema never produces a wrong type.
func tsType(v any, indent string) string {
	m, ok := schemaMap(v)
	if !ok {
		return "unknown"
	}
	if c, ok := m["const"]; ok {
		return jsonLiteral(c)
	}
	if list, ok := m["enum"].([]any); ok && len(list) > 0 {
		parts := make([]string, 0, len(list))
		for _, e := range list {
			parts = append(parts, jsonLiteral(e))
		}
		return strings.Join(parts, " | ")
	}
	for _, key := range []string{"anyOf", "oneOf"} {
		if list, ok := m[key].([]any); ok && len(list) > 0 {
			parts := make([]string, 0, len(list))
			for _, s := range list {
				parts = append(parts, tsType(s, indent))
			}
			return strings.Join(parts, " | ")
		}
	}
	types := schemaTypes(m)
	if len(types) == 0 {
		return "unknown"
	}
	parts := make([]string, 0, len(types))
	for _, t := range types {
		parts = append(parts, tsSingleType(t, m, indent))
	}
	return strings.Join(parts, " | ")
}

func tsSingleType(t string, m map[string]any, indent string) string {
	switch t {
	case "string":
		return "string"
	case "number", "integer":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		item := tsType(m["items"], indent)
		if strings.ContainsAny(item, "|{") {
			return "Array<" + item + ">"
		}
		return item + "[]"
	case "object":
		names, props := sortedProperties(m)
		extra, extraIsSchema := schemaMap(m["additionalProperties"])
		if len(names) == 0 {
			if extraIsSchema {
				return "Record<string, " + tsType(extra, indent) + ">"
			}
			return "Record<string, unknown>"
		}
		required := requiredSet(m)
		inner := indent + "  "
		var b strings.Builder
		b.WriteString("{\n")
		for _, name := range names {
			opt := "?"
			if required[name] {
				opt = ""
			}
			fmt.Fprintf(&b, "%s%s%s: %s;\n", inner, tsKey(name), opt, tsType(props[name], inner))
		}
		b.WriteString(indent + "}")
		return b.String()
	}
	return "unknown"
}

// ---- Python ----

var pyIdent = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

var pyKeywords = map[string]bool{
	"False": true, "None": true, "True": true, "and": true, "as": true, "assert": true, "async": true, "await": true,
	"break": true, "class": true, "continue": true, "def": true, "del": true, "elif": true, "else": true, "except": true,
	"finally": true, "for": true, "from": true, "global": true, "if": true, "import": true, "in": true, "is": true,
	"lambda": true, "nonlocal": true, "not": true, "or": true, "pass": true, "raise": true, "return": true, "try": true,
	"while": true, "with": true, "yield": true,
}

func pyAttr(name string) bool { return pyIdent.MatchString(name) && !pyKeywords[name] }

type pyTypes struct {
	defs  []string
	names map[string]bool
}

func (p *pyTypes) uniqueName(base string) string {
	name := base
	for i := 2; p.names[name]; i++ {
		name = fmt.Sprintf("%s%d", base, i)
	}
	p.names[name] = true
	return name
}

func pythonFunctionTypes(callees []typedCallee) string {
	p := &pyTypes{names: map[string]bool{}}
	type alias struct{ stem, input, output string }
	aliases := make([]alias, 0, len(callees))
	for _, c := range callees {
		stem := typeName(c.name)
		in := p.pyType(c.input, stem+"Input", true)
		out := p.pyType(c.output, stem+"Output", true)
		aliases = append(aliases, alias{stem, in, out})
	}
	var b strings.Builder
	b.WriteString("\"\"\"" + functionTypesHeader + "\"\"\"\n\n")
	b.WriteString("from __future__ import annotations\n\n")
	b.WriteString("from collections.abc import Mapping\n")
	b.WriteString("from typing import Any, Literal, NotRequired, Protocol, TypedDict, cast\n\n")
	b.WriteString("from faas_sdk.functions_runtime import FunctionClient, FunctionInvocation\n")
	b.WriteString("from faas_sdk.functions_runtime import functions as _functions\n\n")
	for _, def := range p.defs {
		b.WriteString(def + "\n")
	}
	for _, a := range aliases {
		if a.input != a.stem+"Input" {
			fmt.Fprintf(&b, "%sInput = %s\n", a.stem, a.input)
		}
		if a.output != a.stem+"Output" {
			fmt.Fprintf(&b, "%sOutput = %s\n", a.stem, a.output)
		}
	}
	if len(aliases) > 0 {
		b.WriteString("\n")
	}
	opts := "*, path: str = ..., headers: Mapping[str, str] | None = ..."
	for _, a := range aliases {
		fmt.Fprintf(&b, "\nclass %sClient(Protocol):\n", a.stem)
		fmt.Fprintf(&b, "    async def call(self, input: %sInput, %s) -> %sOutput: ...\n", a.stem, opts, a.stem)
		fmt.Fprintf(&b, "    def call_sync(self, input: %sInput, %s) -> %sOutput: ...\n", a.stem, opts, a.stem)
		fmt.Fprintf(&b, "    async def send(self, input: %sInput, %s, on_complete: str | None = ...) -> FunctionInvocation: ...\n", a.stem, opts)
		fmt.Fprintf(&b, "    def send_sync(self, input: %sInput, %s, on_complete: str | None = ...) -> FunctionInvocation: ...\n\n", a.stem, opts)
	}
	b.WriteString("\nclass GregaleFunctions(Protocol):\n")
	b.WriteString("    \"\"\"The functions this function may call; a name that is not an identifier is reached by item.\"\"\"\n\n")
	for i, c := range callees {
		if pyAttr(c.name) {
			fmt.Fprintf(&b, "    %s: %sClient\n", c.name, aliases[i].stem)
		}
	}
	b.WriteString("\n    def __getitem__(self, name: str) -> FunctionClient: ...\n\n\n")
	b.WriteString("functions: GregaleFunctions = cast(\"GregaleFunctions\", _functions)\n")
	return b.String()
}

// pyType returns the annotation for v. Objects with properties become named
// TypedDicts, defined before their first use; top marks a function's own
// input or output, whose TypedDict takes the stem name.
func (p *pyTypes) pyType(v any, name string, top bool) string {
	m, ok := schemaMap(v)
	if !ok {
		return "Any"
	}
	if c, ok := m["const"]; ok {
		if lit, ok := pyLiteral(c); ok {
			return "Literal[" + lit + "]"
		}
		return "Any"
	}
	if list, ok := m["enum"].([]any); ok && len(list) > 0 {
		parts := make([]string, 0, len(list))
		for _, e := range list {
			lit, ok := pyLiteral(e)
			if !ok {
				return "Any"
			}
			parts = append(parts, lit)
		}
		return "Literal[" + strings.Join(parts, ", ") + "]"
	}
	for _, key := range []string{"anyOf", "oneOf"} {
		if list, ok := m[key].([]any); ok && len(list) > 0 {
			parts := make([]string, 0, len(list))
			for i, s := range list {
				parts = append(parts, p.pyType(s, fmt.Sprintf("%sOption%d", name, i+1), false))
			}
			return strings.Join(parts, " | ")
		}
	}
	types := schemaTypes(m)
	if len(types) == 0 {
		return "Any"
	}
	parts := make([]string, 0, len(types))
	for _, t := range types {
		parts = append(parts, p.pySingleType(t, m, name, top && len(types) == 1))
	}
	return strings.Join(parts, " | ")
}

func (p *pyTypes) pySingleType(t string, m map[string]any, name string, top bool) string {
	switch t {
	case "string":
		return "str"
	case "integer":
		return "int"
	case "number":
		return "float"
	case "boolean":
		return "bool"
	case "null":
		return "None"
	case "array":
		return "list[" + p.pyType(m["items"], name+"Item", false) + "]"
	case "object":
		names, props := sortedProperties(m)
		extra, extraIsSchema := schemaMap(m["additionalProperties"])
		if len(names) == 0 {
			if extraIsSchema {
				return "dict[str, " + p.pyType(extra, name+"Value", false) + "]"
			}
			return "dict[str, Any]"
		}
		className := name
		if !top || p.names[name] {
			className = p.uniqueName(name)
		} else {
			p.names[name] = true
		}
		required := requiredSet(m)
		fields := make([]string, 0, len(names))
		for _, prop := range names {
			annotation := p.pyType(props[prop], className+typeName(prop), false)
			if !required[prop] {
				annotation = "NotRequired[" + annotation + "]"
			}
			fields = append(fields, fmt.Sprintf("    %s: %s,", jsonLiteral(prop), annotation))
		}
		// The functional form takes any key, including ones that are not
		// Python identifiers or are keywords.
		p.defs = append(p.defs, fmt.Sprintf("%s = TypedDict(%s, {\n%s\n})\n", className, jsonLiteral(className), strings.Join(fields, "\n")))
		return className
	}
	return "Any"
}

func pyLiteral(v any) (string, bool) {
	switch t := v.(type) {
	case string:
		return jsonLiteral(t), true
	case bool:
		if t {
			return "True", true
		}
		return "False", true
	case nil:
		return "None", true
	case float64:
		if t == float64(int64(t)) {
			return fmt.Sprintf("%d", int64(t)), true
		}
	}
	return "", false
}
