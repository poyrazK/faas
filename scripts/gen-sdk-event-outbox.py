#!/usr/bin/env python3
"""Package the existing Go application outbox DDL and shared SQL for both SDKs."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs() -> dict[Path, str]:
    schema = (ROOT / "sdk/go/preview/event_outbox_schema.sql").read_text() + "\n" + (ROOT / "sdk/go/preview/event_outbox_payload_schema.sql").read_text()
    sql = json.loads((ROOT / "sdk/request-contracts/event-outbox-sql.json").read_text())
    def dump(value: object) -> str:
        return json.dumps(value, ensure_ascii=False, indent=2)
    return {
        ROOT / "sdk/go/preview/testdata/event_outbox.json": (ROOT / "sdk/request-contracts/event-outbox.json").read_text(),
        ROOT / "sdk/node/src/event-outbox-protocol.ts": "// Generated by scripts/gen-sdk-event-outbox.py; DO NOT EDIT.\n"
        + "export const eventOutboxSchema = " + json.dumps(schema) + ";\n"
        + "export const outboxSQL = " + dump(sql) + " as const;\n",
        ROOT / "sdk/python/faas_sdk/preview/_event_outbox_protocol.py": "# Generated by scripts/gen-sdk-event-outbox.py; DO NOT EDIT.\n# fmt: off\n"
        + "EVENT_OUTBOX_SCHEMA = " + json.dumps(schema) + "\nSQL = " + dump(sql) + "\n# fmt: on\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, source in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != source:
                raise SystemExit(f"Outbox protocol drift: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source)
    print("SDK event outbox schema and SQL agree")
