#!/usr/bin/env python3
"""Generate the matching SDK receipt schema/queries from shared application SQL."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "sdk/request-contracts/stripe-webhook.sql"


def sources() -> dict[Path, str]:
    sql = json.loads(
        (ROOT / "sdk/request-contracts/stripe-webhook-sql.json").read_text()
    )
    schema = SCHEMA.read_text()
    return {
        ROOT
        / "sdk/node/src/stripe-webhook-protocol.ts": "// Generated by scripts/gen-sdk-stripe-webhook.py; DO NOT EDIT.\nexport const stripeWebhookSchema = "
        + json.dumps(schema)
        + ";\nexport const stripeWebhookSQL = "
        + json.dumps(sql, indent=2)
        + " as const;\n",
        ROOT
        / "sdk/python/faas_sdk/preview/_stripe_webhook_protocol.py": "# Generated by scripts/gen-sdk-stripe-webhook.py; DO NOT EDIT.\n# fmt: off\nSTRIPE_WEBHOOK_SCHEMA = "
        + json.dumps(schema)
        + "\nSQL = "
        + json.dumps(sql, indent=2)
        + "\n# fmt: on\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in sources().items():
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f"Stripe webhook protocol drift: {path}")
        else:
            path.write_text(text)
    print("SDK Stripe receipt schema and SQL agree")
