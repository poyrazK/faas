#!/usr/bin/env python3
"""Generate the matching SDK pipeline tool receipt schema/queries from shared application SQL."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "sdk/request-contracts/pipeline-tools.sql"


def sources() -> dict[Path, str]:
    sql = json.loads(
        (ROOT / "sdk/request-contracts/pipeline-tool-sql.json").read_text()
    )
    schema = SCHEMA.read_text()
    tasks = SCHEMA.with_name("pipeline-tasks.sql").read_text()
    recovery = SCHEMA.with_name("pipeline-task-recovery.sql").read_text()
    handoffs = SCHEMA.with_name("pipeline-task-handoffs.sql").read_text()
    wire = json.loads(
        (ROOT / "sdk/request-contracts/pipeline-tool-wire.json").read_text()
    )
    return {
        ROOT
        / "sdk/node/src/pipeline-tool-protocol.ts": "// Generated by scripts/gen-sdk-pipeline-tool.py; DO NOT EDIT.\nexport const pipelineToolSchema = "
        + json.dumps(schema)
        + ";\nexport const pipelineTaskSchema = "
        + json.dumps(tasks)
        + ";\nexport const pipelineTaskRecoverySchema = "
        + json.dumps(recovery)
        + ";\nexport const pipelineTaskHandoffSchema = "
        + json.dumps(handoffs)
        + ";\nexport const pipelineToolSQL = "
        + json.dumps(sql, indent=2)
        + " as const;\nexport const pipelineToolWire = "
        + json.dumps(wire, indent=2)
        + " as const;\n",
        ROOT
        / "sdk/python/faas_sdk/preview/_pipeline_tool_protocol.py": "# Generated by scripts/gen-sdk-pipeline-tool.py; DO NOT EDIT.\n# fmt: off\nfrom typing import Any\n\nPIPELINE_TOOL_SCHEMA = "
        + json.dumps(schema)
        + "\nPIPELINE_TASK_SCHEMA = "
        + json.dumps(tasks)
        + "\nPIPELINE_TASK_RECOVERY_SCHEMA = "
        + json.dumps(recovery)
        + "\nPIPELINE_TASK_HANDOFF_SCHEMA = "
        + json.dumps(handoffs)
        + "\nSQL = "
        + json.dumps(sql, indent=2)
        + "\nWIRE: dict[str, Any] = "
        + repr(wire)
        + "\n# fmt: on\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in sources().items():
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f"Pipeline tool protocol drift: {path}")
        else:
            path.write_text(text)
    print("SDK Pipeline tool receipt schema and SQL agree")
