//go:build ignore

// Regenerate the leaf SDK's trusted capture probes after a source contract change.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"

	"github.com/onebox-faas/faas/pkg/api"
	"github.com/onebox-faas/faas/pkg/datarepair"
)

func main() {
	check := flag.Bool("check", false, "verify generated probes are current")
	flag.Parse()
	raw := datarepair.CaptureReadinessProgram()
	ts := append([]byte("// Code generated by scripts/gen-data-repair-readiness.go; DO NOT EDIT.\nexport const captureReadinessProbe: { version: number; timeout_ms: number; max_response_bytes: number; max_objects: number; max_table_bytes: number; max_context_bytes: number; finding_ids: string[]; messages: Record<string, {id: string; status: string; summary: string; action: string}>; setup_sql: string; catalog_sql: string; enrollment_sql: string; python_catalog_sql: string; python_enrollment_sql: string } = "), bytes.TrimSpace(raw)...)
	ts = append(ts, []byte(";\n")...)
	goLimits := []byte(fmt.Sprintf("// Code generated by scripts/gen-data-repair-readiness.go; DO NOT EDIT.\npackage preview\n\nconst (\n\tdataRepairContextMaxBytes = %d\n\tdataRepairTableMaxBytes = %d\n)\n", api.DataRepairCaptureContextMaxBytes, api.DataRepairSourceMaxFilterBytes))
	goLimits, err := format.Source(goLimits)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	pythonLimits := []byte(fmt.Sprintf("# Code generated by scripts/gen-data-repair-readiness.go; DO NOT EDIT.\nCONTEXT_MAX_BYTES = %d\nTABLE_MAX_BYTES = %d\n", api.DataRepairCaptureContextMaxBytes, api.DataRepairSourceMaxFilterBytes))
	for path, content := range map[string][]byte{"sdk/go/preview/data_repair_readiness_probe.json": raw, "sdk/python/faas_sdk/preview/data_repair_readiness_probe.json": raw, "sdk/node/src/data-repair-readiness-probe.ts": ts, "sdk/go/preview/data_repair_limits.go": goLimits, "sdk/python/faas_sdk/preview/data_repair_limits.py": pythonLimits} {
		if *check {
			existing, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(existing, content) {
				fmt.Fprintln(os.Stderr, "stale capture readiness probe:", path)
				os.Exit(1)
			}
			continue
		}
		if err := os.WriteFile(path, content, 0644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}
