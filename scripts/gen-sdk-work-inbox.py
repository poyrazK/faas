#!/usr/bin/env python3
"""Generate the shared work-inbox SQL, schema and wire contract."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def files() -> dict[Path, str]:
    shared = ROOT / "sdk/request-contracts"
    wire = json.loads((shared / "work-inbox-contract.json").read_text())
    follow_up = json.loads((shared / "work-inbox-follow-up-contract.json").read_text())
    sql = json.loads((shared / "work-inbox-sql.json").read_text())
    schema = (shared / "work-inbox.sql").read_text()
    return {
        ROOT / "sdk/node/src/work-inbox-protocol.ts":
            "// Generated by scripts/gen-sdk-work-inbox.py.\n"
            + "export const workInboxSchema = " + json.dumps(schema) + ";\n"
            + "export const workInboxSQL = " + json.dumps(sql, indent=2) + " as const;\n"
            + "export const workInboxSpec = " + json.dumps(wire, indent=2) + " as const;\n"
            + "export const workInboxFollowUpSpec = " + json.dumps(follow_up, indent=2) + " as const;\n",
        ROOT / "sdk/python/faas_sdk/preview/_work_inbox_protocol.py":
            "# Generated by scripts/gen-sdk-work-inbox.py.\nimport json\n\n"
            + "WORK_INBOX_SCHEMA = " + json.dumps(schema) + "\n"
            + "SQL = json.loads(" + json.dumps(json.dumps(sql, separators=(",", ":"))) + ")\n"
            + "SPEC = json.loads(" + json.dumps(json.dumps(wire, separators=(",", ":"))) + ")\n"
            + "FOLLOW_UP_SPEC = json.loads(" + json.dumps(json.dumps(follow_up, separators=(",", ":"))) + ")\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, source in files().items():
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit(f"Work inbox protocol drift: {path}")
        else:
            path.write_text(source)
    print("Work inbox protocol agrees across Node and Python")


if __name__ == "__main__":
    main()
