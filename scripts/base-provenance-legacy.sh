#!/usr/bin/env bash
# Print the frozen list of platform base digests that signed releases pinned
# before images.yml attested its images (ADR-20261029155852 decision 7).
#
# It reads the runtime-bases.env asset of every release published up to and
# including --through. Releases after it pass release.yml's provenance gate
# (#5895), so their digests are attested and never belong in the list. The
# output is committed as images/base-provenance-legacy.txt once and never
# regenerated with a later --through; a change needs an ADR amendment.
set -euo pipefail

repo="poyrazK/faas"
through=""

usage() {
  echo "usage: base-provenance-legacy.sh --through TAG [--repo OWNER/NAME]" >&2
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --through)
      [[ $# -ge 2 ]] || { usage; exit 2; }
      through=$2
      shift 2
      ;;
    --repo)
      [[ $# -ge 2 ]] || { usage; exit 2; }
      repo=$2
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      usage
      exit 2
      ;;
  esac
done
[[ -n "$through" ]] || { usage; exit 2; }

cutoff=$(gh release view "$through" --repo "$repo" --json publishedAt --jq .publishedAt)
[[ -n "$cutoff" ]] || { echo "base-provenance-legacy: no release $through" >&2; exit 1; }

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

gh release list --repo "$repo" --limit 10000 --json tagName,publishedAt \
  --jq ".[] | select(.publishedAt <= \"$cutoff\") | .tagName" > "$work/tags"

# A release without the asset predates the runtime-base contract; its builds
# recorded no digest-pinned base, so it contributes nothing.
while read -r tag; do
  gh release download "$tag" --repo "$repo" --pattern runtime-bases.env \
    --output "$work/$tag.env" 2>/dev/null || true
done < "$work/tags"

{
  echo "# Platform base digests that signed releases pinned before images.yml"
  echo "# attested its images (ADR-20261029155852 decision 7). imaged stages these"
  echo "# without an attestation and reports them as legacy. Frozen: generated by"
  echo "# scripts/base-provenance-legacy.sh --through $through; never append."
  cat "$work"/*.env 2>/dev/null \
    | sed -n 's/^FAAS_DEPLOY_BASE_REF_[A-Z0-9_]*=[^@]*@\(sha256:[0-9a-f]\{64\}\)$/\1/p' \
    | LC_ALL=C sort -u
}
