#!/usr/bin/env bash
# render-release-notes.sh TAG CLI-SHA256SUMS — print a release's GitHub
# Release notes (Markdown) to stdout. release.yml renders them in a shell
# step and hands the file to action-gh-release as body_path: the action's
# `body` input is never shell-expanded, so the checksums have to be read here.
set -euo pipefail

tag="${1:?usage: render-release-notes.sh <tag> <CLI-SHA256SUMS>}"
sums="${2:?usage: render-release-notes.sh <tag> <CLI-SHA256SUMS>}"
repo="${GITHUB_REPOSITORY:-poyrazK/faas}"

case "$tag" in
v[0-9]*.[0-9]*.[0-9]*) ;;
*)
	echo "render-release-notes: $tag is not a release tag" >&2
	exit 1
	;;
esac
[ -s "$sums" ] || {
	echo "render-release-notes: $sums is missing or empty" >&2
	exit 1
}

semver="${tag#v}"
fence='```'
example_archive="gregale_${semver}_linux_amd64.tar.gz"

cat <<EOF
## Gregale ${tag}

Bundled CLI: **gregale ${tag}**

### Install the CLI

${fence}sh
curl -fsSL https://get.gregale.dev | sh
${fence}

Pin this exact release:

${fence}sh
curl -fsSL https://get.gregale.dev | sh -s -- --version ${tag}
${fence}

macOS and Linux, amd64 and arm64. Windows is not supported yet
(ADR-172).

npm: \`npm install -g gregale@${semver}\`, once this release's
\`publish-npm\` job has succeeded. See \`docs/cli-install.md\` for the
channel's dist-tags.

### Checksums

${fence}
$(cat "$sums")
${fence}

### Verify

Download the archive for your platform and \`CLI-SHA256SUMS\` into one
directory, then check the files you downloaded:

${fence}sh
# Linux
sha256sum --ignore-missing -c CLI-SHA256SUMS
# macOS
shasum -a 256 --ignore-missing -c CLI-SHA256SUMS
${fence}

Each \`gregale_<version>_<os>_<arch>.tar.gz\` archive also carries a signed
build provenance attestation. With the GitHub CLI:

${fence}sh
gh attestation verify ${example_archive} -R ${repo}
${fence}

The bare \`gregale\` and \`gregale-darwin-arm64\` binaries are not attested;
verify them by checksum.

### Pin

Workflows generated by the Gregale CLI use an immutable Action SHA
by default. Pass \`--pin-action\` to resolve the current \`v0\` tag at
setup time.

To follow the newest stable release's Action, use its moving tag
(prereleases do not move it):

${fence}yaml
- uses: ${repo}/.github/actions/deploy@v0
  with:
    app: my-app
${fence}

For a direct Action reference with hard reproducibility, pin its
40-character release commit SHA:

${fence}yaml
- uses: ${repo}/.github/actions/deploy@<40-character-commit-sha>
${fence}
EOF
