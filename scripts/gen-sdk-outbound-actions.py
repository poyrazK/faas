#!/usr/bin/env python3
"""Generate the portable application-owned outbound action SQL protocol."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sources() -> dict[Path, str]:
    schema = (ROOT / "sdk/request-contracts/outbound-actions.sql").read_text()
    sql = json.loads(
        (ROOT / "sdk/request-contracts/outbound-action-sql.json").read_text()
    )
    return {
        ROOT
        / "sdk/node/src/outbound-action-protocol.ts": "// Generated by scripts/gen-sdk-outbound-actions.py; DO NOT EDIT.\nexport const outboundActionSchema = "
        + json.dumps(schema)
        + ";\nexport const outboundActionSQL = "
        + json.dumps(sql, indent=2)
        + " as const;\n",
        ROOT
        / "sdk/python/faas_sdk/preview/_outbound_action_protocol.py": "# Generated by scripts/gen-sdk-outbound-actions.py; DO NOT EDIT.\n# fmt: off\nOUTBOUND_ACTION_SCHEMA = "
        + json.dumps(schema)
        + "\nSQL = "
        + json.dumps(sql, indent=2)
        + "\n# fmt: on\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in sources().items():
        if args.check:
            if path.read_text() != text:
                raise SystemExit(f"Outbound action protocol drift: {path}")
        else:
            path.write_text(text)
    print("SDK outbound action schema and SQL agree")
